#!/bin/bash

# ======================================================================
# ДОСТУП К MTProxyL-Panel ЧЕРЕЗ 443 ДОМЕНА ПАНЕЛИ
#
# Та же схема, что у telemt_panel: панель слушает только 127.0.0.1, TLS
# терминирует nginx сертификатом сайта, а попасть внутрь можно по случайному
# префиксу пути на обычном 443. Снаружи новых портов нет.
#
# Требует, чтобы lib/nginx_panel_proxy.sh был подключён раньше: оттуда берутся
# panel_proxy_strip, panel_proxy_insert, panel_proxy_apply_block и
# panel_proxy_verify. Своих копий здесь нет намеренно.
#
# ЧЕМ ПРОЩЕ, ЧЕМ У telemt_panel. Той приходится подделывать <base href> и
# window.__BASE_PATH__ через sub_filter: она собрана под работу от корня и из
# подкаталога отдавала белый экран. MTProxyL-Panel умеет base_path сама — в
# её конфиге стоит тот же префикс, и она срезает его с входящих запросов
# внутри себя. Поэтому proxy_pass передаёт путь КАК ЕСТЬ, вместе с префиксом,
# и никакой подмены тела ответа не нужно. Строка взята из документации автора:
#
#   nginx: location /panel123/ { proxy_pass http://127.0.0.1:8080/panel123/; }
#
# ВАЖНО: префикс здесь и base_path в /etc/mtproxyl-panel/config.toml обязаны
# совпадать. Разойдутся — панель ответит 404 на собственные ресурсы, причём
# страница входа откроется, а дальше ничего работать не будет.
# ======================================================================

MTPL_PROXY_BEGIN="# >>> VSM MTProxyL-Panel proxy — не редактируй вручную"
MTPL_PROXY_END="# <<< VSM MTProxyL-Panel proxy"

mtpl_proxy_render() {
    local prefix="$1" port="$2"

    cat << EOF
${MTPL_PROXY_BEGIN}
    location /${prefix}/ {
        # Со слэшем и С префиксом: панель срезает его сама по base_path.
        # Убрать префикс здесь (как сделано для telemt_panel) значит отдать ей
        # путь от корня, которого она не ждёт, — получите 404 на всё.
        proxy_pass http://127.0.0.1:${port}/${prefix}/;

        # ВОЗВРАЩАЕМ ПРЕФИКС В Location.
        #
        # Панель отдаёт перенаправления от КОРНЯ, без своего base_path: запрос
        # /<префикс>/api/telemt получает "Location: /api/telemt/". Так устроен
        # http.ServeMux в Go — он срезает префикс, а канонический путь со
        # слэшем строит уже от того, что осталось. Браузер честно идёт по
        # этому адресу, тот не попадает ни в один location, и nginx отвечает
        # 404 на совершенно исправную панель.
        #
        # Замерено на приёмке 27.08.2026: прямо в панель тот же путь отдаёт
        # 401 (то есть работает и защищён), а через nginx — 301 в никуда.
        # Ровно тот случай, ради которого заведена позиция реестра
        # panel_prefix: страница входа открывается, а часть путей отдаёт 404,
        # и искать причину можно долго.
        #
        # Отрицательный просмотр вперёд обязателен: без него Location, уже
        # содержащий префикс, получил бы второй такой же.
        proxy_redirect ~^/(?!${prefix}/)(.*)$ /${prefix}/\$1;


        # НЕ ДАЁМ ПОДМЕНИТЬ ОТВЕТ ПАНЕЛИ.
        #
        # 3x-ui-pro ставит на весь server{} маскировку:
        #   error_page 400 401 402 403 500 501 502 503 504 =404 /404;
        #   proxy_intercept_errors on;
        # Смысл её понятен — снаружи сервер обязан выглядеть обычным сайтом, и
        # любая ошибка превращается в 404. Но директивы наследуются в наш
        # location, и ответы ПАНЕЛИ подменялись тоже.
        #
        # Замерено на приёмке 27.08.2026 по upstream_status в логе nginx:
        # панель отдавала
        # 401 «missing session cookie», а клиент получал 404. Для REST это
        # смертельно: приложение узнаёт «надо войти» именно по 401, а 404
        # означает «такого пути нет». Снаружи всё выглядело как исправная
        # панель с наглухо неработающим API — форма входа открывается,
        # ресурсы грузятся, а данных нет и причина не названа.
        #
        # Маскировку это не ослабляет: путь сюда секретный, и кто его знает,
        # тот и так видит форму входа. Сам автор 3x-ui-pro выключает перехват
        # там, где ему нужны настоящие коды.
        proxy_intercept_errors off;
        proxy_http_version 1.1;

        proxy_set_header Host              \$host;
        proxy_set_header X-Real-IP         \$remote_addr;
        proxy_set_header X-Forwarded-For   \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;

        # Панель тянет живые данные потоком: трафик, состояние писателей,
        # журнал. Без апгрейда соединение рвётся по таймауту, и графики
        # замирают БЕЗ сообщения об ошибке — то есть выглядит как «данные не
        # меняются», а не как поломка.
        proxy_set_header Upgrade           \$http_upgrade;
        proxy_set_header Connection        "upgrade";
        proxy_read_timeout 3600s;
        proxy_send_timeout 3600s;
        proxy_buffering off;
    }
${MTPL_PROXY_END}
EOF
}

# ----------------------------------------------------------------------
# Подключение. Аргументы: vhost, префикс, порт панели.
# ----------------------------------------------------------------------
mtpl_proxy_apply() {
    local vhost="$1" prefix="$2" port="$3"

    if ! printf '%s' "$prefix" | grep -qE '^[A-Za-z0-9_-]+$'; then
        echo "недопустимый префикс пути MTProxyL-Panel: '$prefix'" >&2
        return 1
    fi
    if ! printf '%s' "$port" | grep -qE '^[0-9]+$'; then
        echo "нужен числовой порт MTProxyL-Panel (получено '$port')" >&2
        return 1
    fi

    panel_proxy_apply_block "$vhost" "$MTPL_PROXY_BEGIN" "$MTPL_PROXY_END" \
        "$(mtpl_proxy_render "$prefix" "$port")" "MTProxyL-Panel"
}

mtpl_proxy_remove() {
    panel_proxy_remove "$1" "$MTPL_PROXY_BEGIN" "$MTPL_PROXY_END"
}

# ----------------------------------------------------------------------
# Чтение настроек панели из её собственного конфига.
#
# Не спрашиваем и не храним у себя: единственный источник правды — тот файл,
# по которому панель реально работает. Расхождение здесь даёт неработающий
# адрес при полностью исправной панели, и искать причину придётся долго.
# ----------------------------------------------------------------------
MTPL_PANEL_CONF="${MTPL_PANEL_CONF:-/etc/mtproxyl-panel/config.toml}"

mtpl_panel_prefix() {
    [ -r "$MTPL_PANEL_CONF" ] || return 0
    sed -n 's/^[[:space:]]*base_path[[:space:]]*=[[:space:]]*"\/\{0,1\}\([^"]*\)".*/\1/p' \
        "$MTPL_PANEL_CONF" | head -1 | tr -d '/'
}

# Адрес, по которому панель открывается снаружи. Собирается из домена панели
# VSM и префикса из ЕЁ конфига: два источника, но оба единственно верные —
# домен знает только VSM, префикс только панель.
#
# Пусто, если чего-то из двух нет: печатать половину адреса хуже, чем не
# печатать ничего.
mtpl_panel_url() {
    local conf="${VSM_TELEMT_CONF:-/etc/vsm/telemt.conf}" domain prefix
    [ -r "$conf" ] || return 0
    domain="$(grep -m1 -oP '^DOMAIN_PANEL=\K.*' "$conf" 2>/dev/null | tr -d "\"'")"
    prefix="$(mtpl_panel_prefix)"
    [ -n "$domain" ] && [ -n "$prefix" ] || return 0
    printf 'https://%s/%s/' "$domain" "$prefix"
}

# Логин администратора панели. Пароль ОТДАТЬ НЕЛЬЗЯ и пытаться не надо: в
# конфиге лежит только его хэш. Это не недоработка, а свойство панели, и
# честнее сказать об этом на экране, чем показывать пустое поле.
#
# Ключ username в этом файле один (секция [auth]), поэтому берём его без
# разбора секций. Появится второй — увидим не тот логин; проверяется это
# мгновенно, а усложнять чтение ради гипотезы не стоит.
mtpl_panel_user() {
    [ -r "$MTPL_PANEL_CONF" ] || return 0
    sed -n 's/^[[:space:]]*username[[:space:]]*=[[:space:]]*"\([^"]*\)".*/\1/p' \
        "$MTPL_PANEL_CONF" | head -1
}

mtpl_panel_port() {
    [ -r "$MTPL_PANEL_CONF" ] || return 0
    sed -n 's/^[[:space:]]*listen[[:space:]]*=[[:space:]]*"[^":]*:\([0-9]\+\)".*/\1/p' \
        "$MTPL_PANEL_CONF" | head -1
}

# ----------------------------------------------------------------------
# Создать секретный путь панели, если его нет.
#
# Установщик автора base_path не спрашивает и не пишет — панель работает от
# корня. Пока это так, спрятать её за префикс на 443 нельзя: nginx отдаст ей
# путь вместе с префиксом, а она такого не ждёт и ответит 404 на всё. До сих
# пор ключ дописывали руками, и это был единственный шаг установки, который
# нигде не описан и потому забывается.
#
# Печатает созданный префикс. Пусто и не-ноль — если что-то не вышло.
# Проверка фактом обязательна: конфиг мог не перечитаться, и тогда nginx
# показывал бы на путь, которого панель не знает.
# ----------------------------------------------------------------------
mtpl_panel_set_prefix() {
    local prefix="$1" tmp
    [ -w "$MTPL_PANEL_CONF" ] || { echo "нет доступа к $MTPL_PANEL_CONF" >&2; return 1; }
    if ! printf '%s' "$prefix" | grep -qE '^[A-Za-z0-9_-]+$'; then
        echo "недопустимый префикс: '$prefix'" >&2
        return 1
    fi

    cp -p "$MTPL_PANEL_CONF" "${MTPL_PANEL_CONF}.vsm-bak" || return 1
    tmp="$(mktemp "${MTPL_PANEL_CONF}.XXXXXX")" || return 1

    # Ключ уже есть — ЗАМЕНЯЕМ его, а не дописываем второй.
    #
    # Прежде функция умела только вписывать новый ключ и звалась лишь при
    # первичной настройке. Но менять путь приходится и потом: он печатается на
    # экран целиком (так задумано — иначе им нельзя пользоваться), а значит
    # рано или поздно попадает в переписку, в скриншот или в чужие руки. Так и
    # вышло на приёмке 23.08.2026. Со старым кодом смена дала бы ДВА ключа
    # base_path в одном файле: панель прочла бы один, мы проверяли бы другой.
    #
    # Две ветки, а не одно хитрое выражение: вставка обязана попасть ДО первой
    # [секции], иначе ключ достанется чужой секции, — а замена обязана
    # остаться на своём месте. Совместить это в одном проходе можно, но тогда
    # порядок правил решает исход, и ошибка в нём молча даёт дубль.
    if grep -qE '^[[:space:]]*base_path[[:space:]]*=' "$MTPL_PANEL_CONF"; then
        awk -v p="$prefix" '
            /^[[:space:]]*base_path[[:space:]]*=/ && !done {
                print "base_path = \"/" p "\""; done = 1; next
            }
            { print }
        ' "$MTPL_PANEL_CONF" > "$tmp" || { rm -f "$tmp"; return 1; }
    else
        awk -v p="$prefix" '
            /^[[:space:]]*\[/ && !done { print "base_path = \"/" p "\""; done = 1 }
            { print }
            END { if (!done) print "base_path = \"/" p "\"" }
        ' "$MTPL_PANEL_CONF" > "$tmp" || { rm -f "$tmp"; return 1; }
    fi
    chown --reference="$MTPL_PANEL_CONF" "$tmp" 2>/dev/null
    chmod --reference="$MTPL_PANEL_CONF" "$tmp" 2>/dev/null
    mv -f "$tmp" "$MTPL_PANEL_CONF" || { rm -f "$tmp"; return 1; }

    systemctl restart mtproxyl-panel >/dev/null 2>&1
    # Панели нужно время подняться: спросим сразу — получим ответ от ещё не
    # перечитавшего конфиг процесса.
    sleep 2

    # Проверяем ДВАЖДЫ: файл и живую панель.
    #
    # Одного чтения файла мало, хотя раньше здесь было только оно. Файл — это
    # то, что записали МЫ; он подтверждает нашу же запись и ничего не говорит о
    # том, приняла ли её панель. Она могла не перечитать конфиг, могла счесть
    # ключ незнакомым (base_path нигде не документирован — мы опираемся на
    # недокументированное поведение чужого бинаря), могла упасть при старте.
    # Во всех трёх случаях прежняя проверка отвечала «всё хорошо», а снаружи по
    # новому адресу приходил бы 404 при полностью исправном на вид конфиге.
    local got; got="$(mtpl_panel_prefix)"
    if [ "$got" != "$prefix" ]; then
        echo "конфиг записан, но в файле оказался другой префикс — откатываю" >&2
        mv -f "${MTPL_PANEL_CONF}.vsm-bak" "$MTPL_PANEL_CONF"
        systemctl restart mtproxyl-panel >/dev/null 2>&1
        return 1
    fi

    # 404 — это именно «панель такого пути не знает». Любой другой ответ
    # (200, редирект на вход, 401) означает, что путь она приняла.
    local port code
    port="$(mtpl_panel_port)"; port="${port:-8080}"
    code="$(curl -s --max-time 8 -o /dev/null -w '%{http_code}' \
        "http://127.0.0.1:${port}/${prefix}/" 2>/dev/null)" || code=000
    if [ "$code" = "404" ] || [ "$code" = "000" ]; then
        echo "панель не приняла новый путь (ответ ${code}) — откатываю" >&2
        mv -f "${MTPL_PANEL_CONF}.vsm-bak" "$MTPL_PANEL_CONF"
        systemctl restart mtproxyl-panel >/dev/null 2>&1
        return 1
    fi
    rm -f "${MTPL_PANEL_CONF}.vsm-bak"
    printf '%s' "$prefix"
}

# Слушает ли панель только loopback. Отдавать наружу панель, которая и сама
# висит на 0.0.0.0, бессмысленно: секретный префикс не спрячет открытый порт.
mtpl_panel_is_local() {
    [ -r "$MTPL_PANEL_CONF" ] || return 1
    grep -qE '^[[:space:]]*listen[[:space:]]*=[[:space:]]*"127\.0\.0\.1:' "$MTPL_PANEL_CONF"
}
