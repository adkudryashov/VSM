#!/bin/bash

# ======================================================================
# ОФОРМЛЕНИЕ: ПАЛИТРА И ПРИМИТИВЫ ВЫВОДА
#
# Сорсится первым — из lib/common.sh. Порядок важен: семантические имена
# (C_NAME, C_DESC и прочие) присваиваются на этапе загрузки от базовых цветов,
# так что базовые обязаны быть определены выше в этом же файле.
#
# Здесь и только здесь живёт всё, что решает, КАК выглядит вывод. Проверка
# checks/ui.sh следит, чтобы цвет не заводился в обход этого файла.
# ======================================================================

# Числа считаем и печатаем с точкой независимо от локали системы.
# При LANG=ru_RU.UTF-8 разделителем становится запятая: awk выдаёт "1.02966",
# printf такое значение уже не принимает ("invalid number"), а если и напечатает,
# то как "1,0" — и bc спотыкается о запятую. Отсюда были ошибки при выводе
# объёма памяти на главном экране. LC_NUMERIC=C приводит awk, printf и bc
# к одному разделителю. На язык сообщений и формат дат не влияет.
export LC_NUMERIC=C

# Цвета ANSI
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[0;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
GRAY='\033[0;90m'
BOLD='\033[1m'
NC='\033[0m' # No Color

# Без цвета — по общепринятой переменной NO_COLOR либо когда вывод не в
# терминал. Второе нужно не для красоты: меню прогоняются без TTY, и раньше
# escape-коды приходилось вычищать отдельным sed, а часть проверок ловила их
# как часть значения.
if [ -n "${NO_COLOR:-}" ] || [ ! -t 1 ]; then
    RED=''; GREEN=''; YELLOW=''; BLUE=''; CYAN=''; GRAY=''; BOLD=''; NC=''
fi

# ----------------------------------------------------------------------
# ОФОРМЛЕНИЕ: КРАСИМ РОЛЬ, А НЕ СТРОКУ
#
# Правило «синий — имя, серый — описание» живёт здесь одной строкой. До этого
# оно было договорённостью, которую девять файлов толковали каждый по-своему:
# в menus/telemt.sh 54 жёлтых и 52 голубых, в menus/utils.sh один синий на весь
# файл. Сменить палитру теперь — правка в одном месте, а не в девяти.
# ----------------------------------------------------------------------
C_NAME="$BLUE"        # имя пункта, функции, параметра
C_DESC="$GRAY"        # описание, значение, пояснение
C_KEY="$YELLOW"       # клавиша выбора
C_HEAD="$CYAN"        # заголовки и разделители
C_OK="$GREEN"
C_WARN="$YELLOW"
C_DANGER="$RED"

# Учётные данные — ЖИРНЫМ, а не цветом.
#
# Серый на них запрещён: на светлом или низкоконтрастном терминале серый пароль
# нечитаем, и «стандартизация оформления» отнимает функцию ровно там, где она
# нужнее всего. Яркий белый задачу тоже не решает — исчезает на светлом фоне.
# Жирный не меняет цвет вовсе, наследует основной цвет терминала и потому
# читается на любой теме.
C_SECRET="$BOLD"

# Знак разрушающего пункта. Второй признак помимо позиции: правило проекта
# запрещает двигать такие пункты к привычному месту, но позиция сама по себе —
# защита слабая, если пункт всё-таки переехал. Задаётся здесь и подставляется
# самой ui_danger_item, а не вызывающим: иначе он снова разойдётся по файлам.
MARK_DANGER='🧨'

# Определите имена и пути
SCANER_PATH="/root/RealiTLScanner-linux-64"
XUI_SERVICE="x-ui"

# ----------------------------------------------------------------------
# ПРИМИТИВЫ ОТРИСОВКИ
#
# Жили в главном меню, пока подменю рисовали каждое своё. Перенесены сюда до
# покраски, а не после: без общего _pad кириллица разъезжается в каждом файле
# заново, и «единое оформление» превращается в девять независимо съезжающих.
# ----------------------------------------------------------------------

# Дополняет строку пробелами до нужной ширины В СИМВОЛАХ.
#
# printf %-Ns здесь не годится: он считает байты, а кириллица в UTF-8 занимает
# два байта на букву — колонки разъезжались ровно на длину русской подписи.
# Локаль задаётся принудительно: ${#s} считает символы только при UTF-8 локали,
# иначе байты, и при LANG=C «Процессор» даёт 18 вместо 9. Проверено на стенде —
# с этой строкой 9 в обоих случаях.
function ui_pad {
    local LC_ALL=C.UTF-8
    local s="$1" w="$2" n=${#1}
    printf '%s' "$s"
    if [ "$n" -lt "$w" ]; then printf '%*s' $((w - n)) ''; fi
}

# Ширина терминала. Без TTY tput возвращает ошибку, поэтому запасное значение
# задаётся здесь, а не достаётся из пустой строки.
# Порядок источников важен. VSM_COLS — явное переопределение: без него узкий
# терминал нечем проверить, потому что при выводе в пайп tput отвечает не
# шириной окна, а значением из terminfo, и проверка «схлопнулось ли» молча
# проходит на восьмидесяти колонках. Так первая попытка и провалилась.
function ui_cols {
    # Значение кэшируется на экран. Раньше каждый вызов форкал tput, а
    # ui_section, ui_hr, ui_title и ui_narrow зовут его по разу — на главном
    # экране это выходило под два десятка форков за отрисовку. Меню
    # открывается при каждом входе по SSH, так что это была бы регрессия по
    # времени, привнесённая самой переделкой оформления.
    #
    # Кэш сбрасывает ui_title, то есть ровно раз на экран: смену размера окна
    # между экранами это подхватывает, а лишних форков не делает.
    if [[ "${_UI_COLS:-}" =~ ^[0-9]+$ ]]; then echo "$_UI_COLS"; return; fi
    ui_cols_init
    echo "$_UI_COLS"
}

# Считает ширину и кладёт в _UI_COLS. Отдельной функцией — потому что вызов
# через $(...) идёт в подоболочке, и присваивание глобальной переменной внутри
# неё до вызывающего не доживает. Первая редакция кэша именно на этом и
# провалилась молча: замер показал одиннадцать форков tput за отрисовку вместо
# одного, хотя кэш «был».
function ui_cols_init {
    local c
    c="${VSM_COLS:-}"
    if [[ ! "$c" =~ ^[0-9]+$ ]]; then c="$(tput cols 2>/dev/null)" || c=""; fi
    if [[ ! "$c" =~ ^[0-9]+$ ]]; then c="${COLUMNS:-}"; fi
    # Порог 20, а не 40. Прежний откатывал терминал уже сорока колонок на
    # восемьдесят — то есть узкому экрану доставалась самая широкая вёрстка,
    # ровно та каша, ради которой схлопывание и делалось. Ниже двадцати
    # рисовать нечего, там уже не вёрстка виновата.
    if [[ ! "$c" =~ ^[0-9]+$ ]] || [ "$c" -lt 20 ]; then c=80; fi
    if [ "$c" -gt 78 ]; then c=78; fi
    _UI_COLS="$c"
}

# Узкий терминал — признак, а не догадка.
#
# Двухколоночная шапка занимает 78 знаков. На телефоне через SSH и в узком окне
# терминала строка переносится посередине значения, и таблица превращается в
# кашу. Порог 76 взят с запасом на отступ слева: при меньшей ширине пары
# печатаются по одной в строку.
function ui_narrow {
    [ "$(ui_cols)" -lt 76 ]
}

# Разделитель раздела: ── ИМЯ ──────────
function ui_section {
    local title="$1" width n dashes
    local LC_ALL=C.UTF-8
    width=$(ui_cols)
    n=$(( width - ${#title} - 6 ))
    if [ "$n" -lt 3 ]; then n=3; fi
    printf -v dashes '%*s' "$n" ''
    echo -e "${C_HEAD}  ── ${title} ${dashes// /─}${NC}"
}

# Рамка заголовка экрана.
#
# Раньше её рисовали литералами в каждом файле, и ширина расходилась: где-то
# 54 символа, где-то 74. Здесь она одна и считается от терминала.
#
# Значок в заголовке учитывается как один символ, а рисуется как два, поэтому
# центрирование смещается на одну ячейку. Мириться с этим дешевле, чем считать
# ширину значков: точной ширины в терминале не знает никто, кроме самого
# терминала.
function ui_title {
    local title="$1" width inner left right bar
    local LC_ALL=C.UTF-8
    # Перечитываем ширину: заголовок печатается ровно раз на экран, и это
    # единственная точка, где смену размера окна стоит подхватить. Зовём
    # ui_cols_init напрямую, а не через подстановку: в подоболочке кэш бы не
    # сохранился, и все последующие вызовы снова форкали бы tput.
    ui_cols_init
    width="$_UI_COLS"
    inner=$(( width - 2 ))
    printf -v bar '%*s' "$inner" ''
    bar="${bar// /═}"
    left=$(( (inner - ${#title}) / 2 ))
    right=$(( inner - ${#title} - left ))
    if [ "$left" -lt 0 ]; then left=0; fi
    if [ "$right" -lt 0 ]; then right=0; fi
    echo -e "${C_HEAD}╔${bar}╗${NC}"
    printf "%b║%b%*s%b%s%b%*s%b║%b\n" \
        "$C_HEAD" "$NC" "$left" '' "$C_OK" "$title" "$NC" "$right" '' "$C_HEAD" "$NC"
    echo -e "${C_HEAD}╚${bar}╝${NC}"
}

function ui_hr {
    local width dashes
    width=$(ui_cols)
    printf -v dashes '%*s' $((width - 2)) ''
    echo -e "${C_HEAD}  ${dashes// /─}${NC}"
}

# Пункт меню: клавиша, эмодзи, имя, описание.
#
# Эмодзи печатается на своём месте и в выравнивание НЕ входит. Его ширина в
# ячейках зависит от терминала, и посчитать её нечем; выравнивать по нему —
# значит гарантированно разъехаться у кого-то другого. Поэтому колонка описания
# отсчитывается от имени, а эмодзи стоит перед ней: съехать может он сам, но не
# таблица за ним.
#
# Эмодзи с вариационным селектором (U+FE0F) в пунктах запрещены — они
# рендерятся в одну или две ячейки в зависимости от терминала. Стережёт это
# checks/ui.sh.
function ui_item {
    local key="$1" icon="$2" name="$3" desc="${4:-}" width="${5:-22}"
    # Клавиша дополняется до двух знаков: пункт «10» сдвигал всю строку вправо
    # на символ, и колонка значков ломалась ровно там, где список длиннее
    # девяти — то есть в самых больших меню.
    key=$(ui_pad "$key" 2)
    # Без описания имя не дополняется: иначе строка кончается двумя десятками
    # пробелов, которые видны при выделении мышью и в любом diff вывода.
    if [ -z "$desc" ]; then
        echo -e "   ${C_KEY}${key}${NC}  ${icon}  ${C_NAME}${name}${NC}"
        return
    fi
    echo -e "   ${C_KEY}${key}${NC}  ${icon}  ${C_NAME}$(ui_pad "$name" "$width")${NC}${C_DESC}${desc}${NC}"
}

# Разрушающий пункт: красный и со своим знаком. Знак подставляется здесь и
# аргументом не принимается — иначе он снова разойдётся по девяти файлам, а
# смысл метки как раз в том, что она всюду одна и та же.
function ui_danger_item {
    local key="$1" name="$2" desc="${3:-}" width="${4:-22}"
    key=$(ui_pad "$key" 2)
    if [ -z "$desc" ]; then
        echo -e "   ${C_DANGER}${key}${NC}  ${MARK_DANGER}  ${C_DANGER}${name}${NC}"
        return
    fi
    echo -e "   ${C_DANGER}${key}${NC}  ${MARK_DANGER}  ${C_DANGER}$(ui_pad "$name" "$width")${NC}${C_DESC}${desc}${NC}"
}

# Пара «имя — значение».
function ui_kv {
    local name="$1" value="$2" width="${3:-14}"
    echo -e "   ${C_NAME}$(ui_pad "$name" "$width")${NC}${C_DESC}${value}${NC}"
}

# То же для учётных данных: значение жирным, никогда не серым.
function ui_secret {
    local name="$1" value="$2" width="${3:-14}"
    echo -e "   ${C_NAME}$(ui_pad "$name" "$width")${NC}${C_SECRET}${value}${NC}"
}

