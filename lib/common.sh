#!/bin/bash

# ======================================================================
# ЕДИНАЯ ТОЧКА ПОДКЛЮЧЕНИЯ БИБЛИОТЕК
#
# Каждое меню сорсит только этот файл. Разделение на ui/config/deps — дело
# внутреннее: перекладывать функции между ними можно, не трогая девять меню.
#
# Раньше на этом месте был один файл _config_and_utils.sh на 746 строк с
# именем-мешком («конфиг И утилиты»), и лежал он в корне репозитория, откуда
# install.sh маской раскладывал в /usr/local/bin вообще всё подряд — включая
# библиотеки, которые исполнять нельзя, и проверки разработчика, которым на
# боевом сервере делать нечего.
#
# ПОРЯДОК ЗАГРУЗКИ ЗНАЧИМ. ui.sh идёт первым: config.sh и deps.sh печатают
# через палитру. Внутри самого ui.sh семантические цвета присваиваются от
# базовых на этапе загрузки, поэтому разносить его дальше нельзя.
# ======================================================================

# Повторный source безвреден, но и бессмыслен: меню бывает сорснуто дважды,
# если его вызвали из другого меню.
if [ -n "${_VSM_COMMON_LOADED:-}" ]; then return 0 2>/dev/null || exit 0; fi
_VSM_COMMON_LOADED=1

# readlink -f обязателен: /usr/local/bin/vsm — символическая ссылка, и без
# разыменования каталог библиотек искался бы в /usr/local/bin.
VSM_LIB="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"

# Корень репозитория. Отсюда меню находят соседей: menus/, stacks/, tools/,
# bots/.
#
# Прежде каждый файл вычислял свой REPO_DIR сам, и они успели разойтись:
# stacks/bots.sh брал dirname БЕЗ readlink -f. Выстрелить не успело — его
# всегда звали по настоящему пути из menus/bots.sh, — но через симлинк из
# /usr/local/bin (а install.sh раскладывал туда и его тоже) BOTS_DIR указал бы
# в /usr/local/bin/bots, которого не существует. Одно место вместо восьми
# закрывает весь класс.
VSM_ROOT="$(dirname "$VSM_LIB")"

# Отсутствие библиотеки — не повод продолжать.
#
# Раньше source шёл без проверки: при неполной раскладке (оборванное
# обновление, битая ссылка в /usr/local/bin) bash печатал одну строку «No such
# file» и работал дальше. Меню при этом рисовалось, но БЕЗ цветов и без
# функций — то есть первый же пункт падал невнятной ошибкой где-то в середине
# работы, вместо того чтобы сказать правду сразу.
#
# Печатаем в stderr и голым текстом: палитра живёт в ui.sh, а его как раз может
# и не быть.
for _lib in ui.sh config.sh deps.sh panels.sh; do
    if [ ! -r "$VSM_LIB/$_lib" ]; then
        printf 'VSM: не найдена библиотека %s\n' "$VSM_LIB/$_lib" >&2
        printf 'Установка повреждена. Переустановите: bash install.sh\n' >&2
        return 1 2>/dev/null || exit 1
    fi
    # shellcheck source=/dev/null
    if ! source "$VSM_LIB/$_lib"; then
        printf 'VSM: библиотека %s не загрузилась\n' "$VSM_LIB/$_lib" >&2
        return 1 2>/dev/null || exit 1
    fi
done
unset _lib
