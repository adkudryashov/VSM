#!/bin/bash

# ======================================================================
# ОДНА ВЕБ-ПАНЕЛЬ НА СЕРВЕР
#
# У VSM их две на выбор, и обе делают одно: telemt_panel (ставит сам VSM) и
# MTProxyL-Panel (ставит чужой скрипт автора MTProxyL). Раньше они спокойно
# уживались рядом, и это было не решением, а недосмотром.
#
# ЧЕМ ПЛОХИ ДВЕ. Не ресурсами — вместе они едят мегабайт. Плохо то, что каждая
# панель это веб-админка с формой входа: две вместо одной означают вдвое больше
# того, что можно взломать, вдвое больше того, что надо обновлять, и два
# секретных префикса, потеря любого из которых открывает вход. За MTProxyL-Panel
# следят четыре позиции реестра решений; заводить такой же присмотр за второй
# ради того же самого — работа без выигрыша.
#
# ПОЧЕМУ ПОРТЫ РАЗНЫЕ, А НЕ ОДИН. Обе слушают только петлю, снаружи их портов
# не видно, и «унифицировать» тут нечего. А одинаковый порт сделал бы замену
# невозможной: при переходе хочется поднять новую и убедиться, что она
# работает, ДО удаления старой. Вдобавок конфликт вылез бы как «address already
# in use» из глубины чужого установщика — ровно тот невнятный отказ, которого
# мы избегаем везде. Исключительность должна быть явным правилом, а не побочным
# эффектом совпадения портов: сменит автор порт — и защита исчезнет молча.
# ======================================================================

TELEMT_PANEL_UNIT=/etc/systemd/system/telemt-panel.service
MTPL_PANEL_UNIT=/etc/systemd/system/mtproxyl-panel.service

# Установлена ли панель. Смотрим на юнит И на бинарь: юнит может остаться от
# неудачного удаления, а бинарь — лежать без юнита после ручного вмешательства.
# Достаточно одного признака: цель вопроса — «есть ли тут вторая панель», и
# половина панели тоже считается.
panel_telemt_installed() {
    [ -f "$TELEMT_PANEL_UNIT" ] || [ -x /usr/local/bin/telemt-panel ]
}
panel_mtproxyl_installed() {
    [ -f "$MTPL_PANEL_UNIT" ] || [ -x /usr/local/bin/mtproxyl-panel ]
}

panel_human_name() {
    case "$1" in
        telemt)   printf 'telemt_panel' ;;
        mtproxyl) printf 'MTProxyL-Panel' ;;
    esac
}

# ----------------------------------------------------------------------
# Удаление telemt_panel — нашей собственной.
# ----------------------------------------------------------------------
panel_remove_telemt() {
    systemctl disable --now telemt-panel >/dev/null 2>&1
    rm -f "$TELEMT_PANEL_UNIT"
    systemctl daemon-reload >/dev/null 2>&1
    rm -f /usr/local/bin/telemt-panel
    rm -rf /etc/telemt-panel
    # Блок nginx снимаем обязательно: без него 443 продолжал бы проксировать на
    # мёртвый порт, и по секретному адресу открывалась бы ошибка шлюза —
    # то есть подтверждение, что там что-то было.
    command -v panel_proxy_remove >/dev/null 2>&1 && panel_proxy_remove >/dev/null 2>&1
    return 0
}

# ----------------------------------------------------------------------
# Удаление MTProxyL-Panel — ЧУЖОЙ.
#
# Зовём деинсталлятор автора, а не сносим файлы сами: он знает про свои
# каталоги, службы и правила больше, чем мы, и его удаление останется верным
# после его же обновлений. Ручной путь оставлен только на случай, когда
# библиотеки автора на месте нет.
# ----------------------------------------------------------------------
panel_remove_mtproxyl() {
    local lib=/opt/mtproxyl/lib/panel.sh
    if [ -r "$lib" ]; then
        # В подоболочке: библиотека автора вправе объявлять что угодно, и
        # затащить это в наше окружение мы не хотим.
        ( # shellcheck source=/dev/null
          . "$lib" >/dev/null 2>&1
          command -v panel_uninstall >/dev/null 2>&1 && panel_uninstall --no-confirm
        ) >/dev/null 2>&1
    fi
    # Проверяем фактом: деинсталлятор автора мог смениться или не отработать.
    if panel_mtproxyl_installed; then
        systemctl disable --now mtproxyl-panel >/dev/null 2>&1
        rm -f "$MTPL_PANEL_UNIT"
        systemctl daemon-reload >/dev/null 2>&1
        rm -f /usr/local/bin/mtproxyl-panel
        rm -rf /etc/mtproxyl-panel
    fi
    command -v mtpl_proxy_remove >/dev/null 2>&1 && mtpl_proxy_remove >/dev/null 2>&1
    return 0
}

# ----------------------------------------------------------------------
# Страж: вызывается ПЕРЕД установкой панели.
#
# Аргумент — что собираемся ставить: telemt или mtproxyl.
# Возвращает 0, если можно продолжать, и 1, если владелец отказался или
# удаление не удалось. Вызывающий ОБЯЗАН прервать установку на единице:
# поставить вторую панель поверх первой — как раз то, чего мы избегаем.
# ----------------------------------------------------------------------
panel_ensure_exclusive() {
    local target="$1" other other_name
    case "$target" in
        telemt)   other=mtproxyl ;;
        mtproxyl) other=telemt ;;
        *)        return 0 ;;
    esac

    "panel_${other}_installed" || return 0    # второй нет — ставим спокойно

    other_name="$(panel_human_name "$other")"
    echo
    echo -e "${C_WARN:-$YELLOW}На сервере уже стоит другая веб-панель: ${other_name}.${NC}"
    echo -e "${C_DESC:-}  VSM держит только одну: две админки — это вдвое больше того, что можно"
    echo -e "  взломать и надо обновлять, ради одной и той же задачи.${NC}"
    echo
    echo -e "${C_WARN:-$YELLOW}Продолжив, вы УДАЛИТЕ ${other_name}. Вместе с ней уйдут:${NC}"
    echo -e "  • её учётные данные — задать их заново придётся вручную"
    echo -e "  • её секретный префикс в nginx, то есть прежний адрес перестанет работать"
    echo -e "  • её настройки"
    echo
    echo -e "${C_DESC:-}Резервная копия секретов будет снята перед удалением.${NC}"
    echo

    local answer
    read -r -p "Введите БОЛЬШИМИ буквами ДА, чтобы удалить ${other_name}: " answer
    if [ "$answer" != "ДА" ]; then
        echo -e "${C_DESC:-}Отменено. Установка не начиналась, ${other_name} на месте.${NC}"
        return 1
    fi

    # Копия ДО удаления, а не после: в ней остаются учётки удаляемой панели, и
    # это единственный способ вернуть их, если решение окажется поспешным.
    local backup="${VSM_ROOT:-/root/VSM}/tools/vsm-backup.sh"
    [ -x "$backup" ] && bash "$backup" >/dev/null 2>&1 \
        && echo -e "${GREEN:-}  ✓ резервная копия снята${NC}"

    echo -e "${YELLOW:-}  Удаляю ${other_name}…${NC}"
    "panel_remove_${other}"

    # Проверка фактом. Продолжать установку поверх недоудалённой панели нельзя:
    # получится ровно то состояние, которое мы и разбираем, только запутаннее.
    if "panel_${other}_installed"; then
        echo -e "${RED:-}  ✗ ${other_name} удалить не удалось — установка отменена.${NC}"
        echo -e "${C_DESC:-}  Уберите её вручную и повторите.${NC}"
        return 1
    fi
    echo -e "${GREEN:-}  ✓ ${other_name} удалена.${NC}"
    return 0
}
