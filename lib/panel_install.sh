#!/bin/bash

# ======================================================================
# УСТАНОВКА telemt_panel — ОДНА НА ДВА ВЫЗЫВАЮЩИХ
#
# Раньше эти семьдесят строк жили внутри stacks/telemt.sh как этапы 4 и 5, и
# попасть в них можно было единственным путём — установкой ВСЕГО стека с нуля.
# То есть: сняли панель (а её снимает страж исключительности перед установкой
# MTProxyL) — и вернуть её нечем. Только переустановкой стека, которая стирает
# 3x-ui вместе с базой, инбаундами и всеми пользователями.
#
# Владелец сформулировал это прямо: хочу иметь возможность ставить или
# telemt_panel, или MTProxyL-Panel. Правило «одна панель на сервер» такой выбор
# и подразумевало, но выбирать было нечем: одна ставилась сама и только в
# составе стека, вторая — чужой командой мимо VSM.
#
# Поэтому установка вынесена сюда. Стек зовёт её этапом 4, меню — пунктом
# «Веб-панель». Копий не делаем принципиально: ровно так разошлись две копии
# wait_for_apt, и разошлись в опасную сторону — одна ждала, другая молча нет.
#
# ВОЗВРАЩАЕТ КОД, А НЕ УМИРАЕТ. Внутри стека уместен die, внутри меню — нет:
# упавшая функция не должна уносить с собой интерактивное меню. Вызывающий сам
# решает, что делать с единицей.
# ======================================================================

TELEMT_PANEL_INSTALLER_URL="${TELEMT_PANEL_INSTALLER_URL:-https://raw.githubusercontent.com/amirotin/telemt_panel/main/install.sh}"

# ВЕРСИЯ ЗАДАЁТСЯ ЯВНО, И ЭТО НЕ ПИННИНГ РАДИ ПИННИНГА.
#
# Умолчание установщика — «последняя стабильная», то есть 0.6.2. Поставить её
# он не может: контрольные суммы в том релизе названы
# telemt-panel-x86_64-linux-gnu.sha256, а установщик 1.x ищет
# ...tar.gz.sha256 и останавливается словами «Не удалось получить файл
# контрольной суммы». Проверено сухим прогоном дважды 23.09.2026 — свойство
# версии, а не сбой сети. Старый установщик с тега v0.6.2 (21 КБ) умеет только
# интерактивный мастер, --yes и TP_* у него нет вовсе.
#
# То есть выбор был не «свежая или стабильная», а «свежая или слепая лента
# ответов». Решение владельца 23.09.2026 — свежая.
#
# Менять здесь, когда 1.0.0 выйдет из кандидатов.
TELEMT_PANEL_VERSION="${TELEMT_PANEL_VERSION:-v1.0.0-rc.2}"

# Адрес HTTP API движка. Тот же, что проверяет этап 3 установщика стека.
TELEMT_PANEL_API_URL="${TELEMT_PANEL_API_URL:-http://127.0.0.1:9091}"

_pi_log()  { echo -e "${GREEN:-}  ▸${NC:-} $*"; }
_pi_warn() { echo -e "${YELLOW:-}  !${NC:-} $*"; }
_pi_err()  { echo -e "${RED:-}  ✗${NC:-} $*" >&2; }

# Ждём готовности, а не спим наугад: панель поднимается за разное время на
# разном железе, и фиксированный sleep либо тратит время впустую, либо не
# дожидается.
_pi_wait_until() {
    local limit="$1"; shift
    local i=0
    while [ "$i" -lt "$limit" ]; do
        "$@" >/dev/null 2>&1 && return 0
        sleep 1; i=$((i + 1))
    done
    return 1
}

# ----------------------------------------------------------------------
# panel_install_telemt <логин> <пароль> <порт> <домен-панели> <домен-reality> <префикс>
#
# Ставит telemt_panel, переводит её на loopback без своего TLS и подключает к
# 443 домена панели по секретному префиксу. Проверяет фактом на каждом шаге.
# ----------------------------------------------------------------------
panel_install_telemt() {
    local admin_user="$1" admin_pass="$2" port="$3"
    local domain_panel="$4" domain_reality="$5" prefix="$6"

    # need="" ОБЯЗАТЕЛЬНО, а не `local need`.
    #
    # `local need` оставляет переменную НЕустановленной, а установщик стека
    # работает под set -euo pipefail. Там и накопление `need="${need} $fn"`, и
    # сама проверка `[ -n "$need" ]` обращаются к неустановленной переменной —
    # и оболочка убивает скрипт со словами «need: unbound variable» ещё до
    # того, как страж успеет что-нибудь сказать.
    #
    # Срабатывало это ВСЕГДА, независимо от того, подключены библиотеки или
    # нет: проверка падала на самой себе. Из меню функция работала, потому что
    # меню под set -u не ходит — отсюда и месяц незамеченной поломки (файл
    # появился 27.08.2026, поймано на установке с нуля 23.09.2026). Снаружи
    # это выглядело как «панель не установилась», без единого внятного слова.
    # Список — ровно то, что эта функция ЗОВЁТ. panel_proxy_localize ушла из
    # него вместе с вызовом: панель теперь кладёт установщик, а не мы правим
    # после него. Страж, который требует лишнего, однажды откажет на исправной
    # системе — а верить ему после этого перестанут.
    local need="" fn
    for fn in panel_proxy_apply panel_proxy_verify nginx_mask_panel_vhost; do
        declare -F "$fn" >/dev/null 2>&1 || need="${need} $fn"
    done
    if [ -n "$need" ]; then
        _pi_err "не подключены библиотеки nginx:${need}"
        return 1
    fi

    # script(1) больше не нужен: установщик работает без псевдотерминала.
    # Нужен curl — им скачивается сам установщик и им же проверяется результат.
    command -v curl >/dev/null 2>&1 || {
        _pi_err "нужен curl."
        return 1
    }

    local installer
    installer="$(mktemp /tmp/telemt-panel-install.XXXXXX.sh)" || return 1

    if ! curl -fsSL "$TELEMT_PANEL_INSTALLER_URL" -o "$installer" || [ ! -s "$installer" ]; then
        rm -f "$installer"
        _pi_err "не удалось скачать установщик telemt_panel."
        return 1
    fi

    # УСТАНОВЩИКУ ЗАДАЁМ ЗНАЧЕНИЯ, А НЕ ОТВЕЧАЕМ НА ЕГО ВОПРОСЫ.
    #
    # Раньше здесь был псевдотерминал и лента ответов вслепую:
    #     printf '\n\n%s\n%s\n\n\n' "$admin_user" "$admin_pass" | script -qe ...
    # Она держалась на ТОЧНОМ порядке вопросов чужого мастера. Автор добавил
    # выбор сборки (full/lite) и проверку связи с API — лента сдвинулась,
    # проверка получила не тот адрес, а когда ответы кончились, мастер начал
    # вечно брать умолчание «проверить ещё раз»:
    #     1) Check again  2) Change address and header  3) Continue [1]:
    # Установка не падала, а ВИСЕЛА. Замерено 23.09.2026 на установке с нуля.
    #
    # У установщика 1.x есть штатный неинтерактивный режим: --yes плюс
    # переменные TP_*. Он не задаёт вопросов вовсе, поэтому новый вопрос у
    # автора больше ничего не ломает. Заодно уходят: зависимость от script(1),
    # пляска со stty против эха пароля (пароль идёт окружением, а не в
    # терминал) и возможность зависнуть.
    #
    # Версию задаём явно. Умолчание установщика — «последняя стабильная», то
    # есть 0.6.2, а её он поставить НЕ МОЖЕТ: контрольные суммы там названы
    # telemt-panel-x86_64-linux-gnu.sha256, а он ищет ...tar.gz.sha256 и
    # останавливается на «Не удалось получить файл контрольной суммы».
    # Проверено сухим прогоном дважды — это свойство версии, а не сбой сети.
    #
    # TP_OPEN_FIREWALL=no обязателен: панель живёт на петле, открывать её порт
    # наружу незачем, а установщик считает это отдельным явным согласием.
    _pi_log "ставлю telemt_panel ${TELEMT_PANEL_VERSION} (без вопросов)..."
    TP_LANG=ru \
    TP_TELEMT_URL="$TELEMT_PANEL_API_URL" \
    TP_ADMIN_USER="$admin_user" \
    TP_ADMIN_PASSWORD="$admin_pass" \
    TP_LISTEN="127.0.0.1:${port}" \
    TP_TLS_MODE=proxy \
    TP_BASE_PATH=/ \
    TP_RUN_AS=user \
    TP_SUBPAGE=no \
    TP_OPEN_FIREWALL=no \
        sh "$installer" --yes --no-color --version "$TELEMT_PANEL_VERSION" || {
            _pi_err "установщик telemt_panel вернул ошибку (вывод выше)."
            rm -f "$installer"
            return 1
        }
    rm -f "$installer"

    local toml=/etc/telemt-panel/config.toml
    [ -f "$toml" ] || { _pi_err "telemt_panel не создала $toml."; return 1; }

    # ПРОВЕРЯЕМ ФАКТОМ, А НЕ ПРАВИМ ВСЛЕПУЮ.
    #
    # Панель обязана слушать ТОЛЬКО петлю и без своего TLS. Раньше было
    # 0.0.0.0 плюс собственный сертификат домена REALITY, и снаружи это
    # выглядело как админ-форма с валидным сертификатом на нестандартном порту
    # — самый громкий объект на сервере: сканеру хватало одного соединения,
    # чтобы классифицировать IP, и вся работа по маскировке порта telemt
    # теряла смысл. Теперь TLS терминирует nginx на 443 домена панели.
    #
    # Добивались этого правкой конфига после установки (panel_proxy_localize).
    # Больше не правим, и это не лень: в 1.x секция [tls] содержит mode =
    # "http", а не cert_file/key_file, и прежняя правка вырезала бы строку
    # [tls], оставив mode висеть в корне файла. Установщик кладёт нужное сам —
    # значит наше дело убедиться, что положил, и громко сказать, если нет.
    grep -q "^listen[[:space:]]*=[[:space:]]*\"127\.0\.0\.1:${port}\"" "$toml" || {
        _pi_err "панель слушает не петлю — снаружи это видимая админ-форма."
        _pi_err "смотрите listen в ${toml}"
        return 1
    }
    if grep -qE '^[[:space:]]*(cert_file|key_file)[[:space:]]*=' "$toml"; then
        _pi_err "у панели остался собственный TLS — TLS обязан терминировать nginx."
        _pi_err "смотрите секцию [tls] в ${toml}"
        return 1
    fi

    # Снимаем доступ панели к приватным ключам Let's Encrypt.
    #
    # Свой TLS ей больше не нужен, а прежние версии выдавали пользователю
    # telemt-panel права на /etc/letsencrypt через ACL. Установка поверх такой
    # системы оставила бы их: служба, которой ключи не нужны, продолжала бы их
    # читать. Делаем молча и не падаем — права могли и не выдаваться.
    if id telemt-panel >/dev/null 2>&1 && command -v setfacl >/dev/null 2>&1; then
        setfacl -x u:telemt-panel /etc/letsencrypt/live /etc/letsencrypt/archive 2>/dev/null || true
        if [ -n "$domain_reality" ]; then
            setfacl -R -x u:telemt-panel "/etc/letsencrypt/archive/${domain_reality}" 2>/dev/null || true
        fi
    fi

    systemctl is-active --quiet telemt-panel || {
        _pi_err "служба telemt-panel не запустилась — journalctl -u telemt-panel"
        return 1
    }

    # Обращаемся по http: TLS у панели больше нет.
    _pi_wait_until 20 curl -s --max-time 5 "http://127.0.0.1:${port}/" -o /dev/null \
        || _pi_warn "telemt_panel не отвечает на http://127.0.0.1:${port}/ — journalctl -u telemt-panel"
    local code
    code="$(curl -s --max-time 10 "http://127.0.0.1:${port}/" -o /dev/null -w '%{http_code}')" || code=000
    [ "$code" = "200" ] || _pi_warn "telemt_panel вернула $code вместо 200 — journalctl -u telemt-panel"

    # Подключаем панель к 443 домена панели по случайному префиксу пути.
    #
    # Блок вписывается в vhost панели, а тот лежит в sites-enabled — каталоге,
    # который установщик и патч 3x-ui-pro вычищают целиком. Пережить это он, в
    # отличие от маски, не может: nginx не умеет добавлять location в чужой
    # server{} из отдельного файла. Поэтому блок помечен маркерами и
    # переприменяется пунктом меню «Восстановить nginx».
    _pi_log "подключаю панель к 443 домена ${domain_panel}"
    local vhost
    vhost="$(nginx_mask_panel_vhost "$domain_panel")" || {
        _pi_err "не найден vhost домена ${domain_panel} — панель некуда подключить."
        return 1
    }
    panel_proxy_apply "$vhost" "$prefix" "$port" || {
        _pi_err "не удалось подключить telemt_panel к nginx (причина выше)."
        return 1
    }

    local url_check
    if url_check="$(panel_proxy_verify "$domain_panel" "$prefix")"; then
        _pi_log "панель отвечает по своему адресу"
    else
        _pi_warn "панель по адресу через nginx вернула ${url_check} — проверьте вручную."
        _pi_warn "если вёрстка поедет, панель не умеет работать из подкаталога: тогда"
        _pi_warn "оставьте её на loopback и ходите через ssh -L ${port}:127.0.0.1:${port}"
    fi
    return 0
}
