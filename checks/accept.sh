#!/bin/bash
#
# Приёмка меню. Запускается НА СЕРВЕРЕ, где VSM установлен.
#
# Зачем отдельно от checks/ui.sh: та читает исходники, эта запускает. За сессию
# переделки оформления одиннадцать дефектов нашлись так — пять в живом
# терминале, ноль статикой. Читать код оказалось недостаточно.
#
# ЧЕГО ЭТА ПРИЁМКА НЕ ДЕЛАЕТ: она не жмёт разрушающие пункты. Слепо прогнать
# все клавиши подряд на живом сервере значит снести стек — установка, удаление
# и правка фаервола исключены поимённо, а не по догадке.
#
# Запуск: bash checks/accept.sh
# Возврат: 0 — чисто, 1 — есть находки.

# Приёмка лежит в checks/, а гоняет весь репозиторий — поднимаемся на уровень
# выше. Два dirname: первый снимает имя файла, второй каталог checks.
cd "$(dirname "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")")" || exit 1

# Меню запускаются ИЗ РЕПОЗИТОРИЯ, а не из /usr/local/bin.
#
# Прежде здесь стоял BIN=/usr/local/bin, потому что install.sh раскладывал туда
# ссылку на каждый файл. Теперь ссылка ровно одна — vsm, — а меню находят друг
# друга по своему расположению. Заодно приёмку стало можно гонять на копии
# репозитория, не устанавливая её в систему.
FAIL=0
say()  { echo -e "\033[0;36m$*\033[0m"; }
bad()  { echo -e "\033[0;31m  ✗ $*\033[0m"; FAIL=1; }
ok()   { echo -e "\033[0;32m  ✓ $*\033[0m"; }
note() { echo -e "\033[0;90m    $*\033[0m"; }

MENUS=(vsm menus/xui.sh menus/telemt.sh menus/bots.sh
       menus/setup.sh menus/tests.sh menus/utils.sh menus/warp.sh)

# Признаки того, что скрипт сломался, а не отработал. Ищем в выводе, потому что
# код возврата у меню ничего не значит: цикл завершается по X и возвращает 0
# даже если внутри сыпались ошибки.
ERRPAT='command not found|unbound variable|syntax error|No such file or directory|integer expression expected|too many arguments|bad substitution'

# ---------------------------------------------------------------------------
# 1. Каждый экран открывается и не сыплет ошибками
#
# Без TTY и с ограничением по времени: при закрытом stdin цикл меню крутится
# вечно — это уже ловили. Цвет снимается сам, потому что вывод не в терминал.
# ---------------------------------------------------------------------------
say "1. Экраны открываются без ошибок оболочки"
for m in "${MENUS[@]}"; do
    out=$(printf 'X\nX\nX\n' | timeout 40 bash "$m" 2>&1)
    hits=$(grep -inE "$ERRPAT" <<< "$out" | head -3)
    if [ -n "$hits" ]; then
        bad "$m"
        sed 's/^/      /' <<< "$hits"
    elif [ "$(wc -c <<< "$out")" -lt 200 ]; then
        bad "$m: экран почти пуст ($(wc -c <<< "$out") байт) — вероятно, упал молча"
    else
        ok "$m"
    fi
done

# ---------------------------------------------------------------------------
# 2. У каждой показанной клавиши есть ветка обработки
#
# Ровно тот дефект, который владелец нашёл глазами: пункты перегруппировали, а
# клавиши остались прежние. Обратная сторона той же ошибки страшнее — клавиша
# показана, а ветки под неё нет, и нажатие молча ничего не делает.
#
# Проверяем только это направление. «Ветка есть, а пункт не показан» — не
# дефект: во вложенных меню свои case с теми же цифрами.
# ---------------------------------------------------------------------------
say "2. Показанная клавиша имеет ветку обработки"
found=0
for m in "${MENUS[@]}"; do
    keys=$(grep -oE 'ui_(danger_)?item +"[0-9]+"' "$m" 2>/dev/null \
           | grep -oE '[0-9]+' | sort -un)
    for k in $keys; do
        if ! grep -qE "^[[:space:]]*(${k}\)|[0-9|]*\|${k}\)|${k}\|)" "$m"; then
            bad "$m: клавиша ${k} показана, но ветки под неё нет"
            found=1
        fi
    done
done
[ "$found" -eq 0 ] && ok "все показанные клавиши обрабатываются"

# ---------------------------------------------------------------------------
# 3. Безопасные пункты действительно работают
#
# Поимённо и только те, что ничего не меняют. Каждый проверяется по признаку в
# выводе, а не по коду возврата: меню возвращает 0 почти всегда.
# ---------------------------------------------------------------------------
say "3. Безопасные пункты открываются и делают своё"
drive() { # файл ввод признак описание
    local f="$1" keys="$2" want="$3" desc="$4" out
    out=$(printf '%b' "$keys" | timeout 40 bash "$f" 2>&1)
    if grep -qiE "$ERRPAT" <<< "$out"; then
        bad "$desc: ошибка оболочки"
        grep -inE "$ERRPAT" <<< "$out" | head -2 | sed 's/^/      /'
    elif grep -qiE "$want" <<< "$out"; then
        ok "$desc"
    else
        bad "$desc: в выводе нет признака «${want}»"
    fi
}
#
# Признак берётся из вывода ДЕЙСТВИЯ, а не из названия пункта.
#
# Первая редакция искала «Активные порты» — и проходила, потому что эта строка
# есть в самом списке меню. Проверка «работает ли пункт» отвечала «да», ни разу
# его не открыв. Плюс ввод начинался с X, который выходит из меню сразу же: до
# нужной клавиши дело не доходило вовсе.
#
# Отсюда правило для этого файла: признак обязан быть строкой, которой в
# списке пунктов НЕТ.
drive menus/utils.sh  '4\n3\n\nX\n'  'Netid|LISTEN|UNCONN'    'утилиты: порты (клавиша 4)'
drive menus/utils.sh  '5\n\nX\n'     'Проверка IP'            'утилиты: внешний адрес (клавиша 5)'
drive menus/xui.sh    '3\nX\nX\n'    'УЧЁТНЫЕ ДАННЫЕ ПАНЕЛИ'  'X-UI: учётные данные (клавиша 3)'
drive menus/telemt.sh '7\n\nX\n'     'УЧЁТНЫЕ ДАННЫЕ СТЕКА'   'telemt: учётные данные (клавиша 7)'

# ---------------------------------------------------------------------------
# 3б. Обработчики действий внутри подменю
#
# Переделка оформления шла по ГЛАВНЫМ экранам, а `clear 2>/dev/null` был
# прогнан слепым sed по девяти файлам. Значит обработчики трогали, но не
# открывали ни разу.
#
# Здесь открывается каждый экран второго уровня и проверяется, что оболочка не
# сыплет ошибками. Ничего не подтверждается: там, где обработчик спрашивает
# подтверждение, ввод обрывается пустой строкой и выходом.
#
# Ищем поломку. Признак экрана — четвёртым аргументом, и там, где он задан,
# проверяется ещё и то, что открылся ИМЕННО ТОТ экран.
#
# ЗАЧЕМ ПРИЗНАК. Экраны здесь адресуются номером клавиши, а номера переезжают
# при каждой перестановке списка. Поймано 27.08.2026: добавление пункта
# «Веб-панель» сдвинуло меню telemt на единицу, и четыре проверки продолжили
# рапортовать об успехе, открывая совершенно другие экраны — «диагностика (3)»
# открывала веб-панель, «MTProxyL (8)» открывала управление службами. Проверка,
# которая проходит после переезда проверяемого, не проверяет ничего.
#
# Признак обязан быть строкой, которой в списке пунктов НЕТ, — иначе он найдётся
# в самом меню, не открывая экрана. Правило то же, что и для drive выше.
#
# Где признака нет, проверка осталась прежней: только поломка. Экраны разные, и
# половина зависит от того, что установлено; выдумывать признак ради галочки
# хуже, чем честно проверять меньше.
# ---------------------------------------------------------------------------
say "3б. Обработчики действий второго уровня"
screen() { # файл ввод описание [признак]
    local out; out=$(printf '%b' "$2" | timeout 60 bash "$1" 2>&1)
    local hits; hits=$(grep -inE "$ERRPAT" <<< "$out" | head -2)
    if [ -n "$hits" ]; then
        bad "$3"
        sed 's/^/      /' <<< "$hits"
        return
    fi
    if [ -n "${4:-}" ] && ! grep -qE "$4" <<< "$out"; then
        bad "$3: открылся не тот экран — нет признака «$4»"
        return
    fi
    ok "$3"
}
screen menus/xui.sh    '4\nX\nX\nX\n'      'X-UI: бэкапы (4)'
screen menus/xui.sh    '5\n1\n\nX\nX\n'    'X-UI: служба, статус (5→1)'
screen menus/xui.sh    '7\nX\nX\nX\n'      'X-UI: AdGuard (7)'
screen menus/telemt.sh '3\nX\nX\n'         'telemt: веб-панель (3)' 'ВЕБ-ПАНЕЛЬ'
screen menus/telemt.sh '4\n\nX\n'          'telemt: диагностика (4)' 'СТАТУС И ДИАГНОСТИКА СТЕКА'
screen menus/telemt.sh '8\n1\n1\n\nX\nX\n' 'telemt: служба telemt, статус (8→1→1)' 'Loaded:|Active:|could not be found'
screen menus/telemt.sh '9\nX\nX\n'         'telemt: MTProxyL (9)' 'SYN-ЛИМИТЕР И ТЮНИНГ'
screen menus/telemt.sh '10\n\n\nX\n'       'telemt: экран пересборки nginx (10, без подтверждения)' 'ПЕРЕСБОРКА NGINX'
screen menus/bots.sh   '6\n\nX\n'          'боты: настройки (6)'
screen menus/bots.sh   '7\nX\nX\n'         'боты: управление службами (7)'
screen menus/setup.sh  '1\nX\nX\n'         'настройка: BBR (1)'
screen menus/setup.sh  '2\nX\nX\n'         'настройка: ICMP (2)'
screen menus/setup.sh  '3\nX\nX\n'         'настройка: UFW (3, без включения)'
screen menus/setup.sh  '4\nX\nX\n'         'настройка: IPv6 (4, без переключения)'
screen menus/setup.sh  '5\nX\nX\n'         'настройка: SSL (5)'
screen menus/setup.sh  '6\nX\nX\n'         'настройка: часовой пояс (6)'
screen menus/warp.sh   '2\n\nX\n'          'WARP: порт (2)'
screen menus/warp.sh   '4\nX\nX\n'         'WARP: служба (4)'
screen menus/utils.sh  '2\n4\n\nX\n'       'утилиты: ncdu, свой путь (2→4)'
screen menus/utils.sh  '7\n\n\nX\n'        'утилиты: привязка домена (7)'
screen menus/utils.sh  '8\nX\nX\n'         'утилиты: очистка (8, без подтверждения)'

echo
if [ "$FAIL" -eq 0 ]; then
    echo -e "\033[0;32mПриёмка меню: находок нет.\033[0m"
else
    echo -e "\033[0;31mПриёмка меню: есть находки, см. выше.\033[0m"
fi
exit "$FAIL"
