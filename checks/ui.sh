#!/bin/bash
#
# Проверка оформления меню. Ловит ровно те дефекты, которые не видны ни в
# `bash -n`, ни в диффе, а проявляются только в терминале — и потому находились
# по одному, вручную, после каждой правки.
#
# Запуск: bash checks/ui.sh   (из каталога репозитория)
# Возврат: 0 — чисто, 1 — есть находки.

# Проверка лежит в checks/, а проверяет весь репозиторий — поднимаемся на
# уровень выше. Два dirname: первый снимает имя файла, второй каталог checks.
cd "$(dirname "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")")" || exit 1

FILES=(vsm menus/*.sh lib/*.sh)
FAIL=0

say()  { echo -e "\033[0;36m$*\033[0m"; }
bad()  { echo -e "\033[0;31m  ✗ $*\033[0m"; FAIL=1; }
ok()   { echo -e "\033[0;32m  ✓ $*\033[0m"; }

# ---------------------------------------------------------------------------
# 1. Эмодзи с вариационным селектором
#
# U+FE0F просит эмодзи-представление у знака, который по умолчанию текстовый.
# Слушаются его не все терминалы: один рисует две ячейки, другой одну, и
# колонка справа съезжает у половины пользователей. Автор исходного меню
# компенсировал это лишним пробелом после таких значков — то есть подгонял
# вёрстку под свой терминал.
#
# Строки комментариев пропускаются: на экран они не попадают, а значит и
# вёрстку не ломают. Прежняя редакция считала весь файл подряд и споткнулась о
# комментарий, который ЦИТИРУЕТ проблемный знак, объясняя, чем тот плох.
# Ложное срабатывание здесь дороже, чем кажется: проверку, которая ругается на
# заведомо безобидное, перестают запускать — ровно так же, как перестали бы
# ждать две минуты у первой её редакции.
# ---------------------------------------------------------------------------
say "1. Эмодзи с вариационным селектором (U+FE0F)"
found=0
for f in "${FILES[@]}"; do
    n=$(LC_ALL=C grep -v '^[[:space:]]*#' "$f" 2>/dev/null \
        | LC_ALL=C grep -c $'\xef\xb8\x8f') || n=0
    if [ "${n:-0}" -gt 0 ]; then
        bad "$f: строк $n"
        LC_ALL=C grep -nv '^[[:space:]]*#' "$f" | LC_ALL=C grep $'\xef\xb8\x8f' \
            | head -3 | sed 's/^/      /'
        found=1
    fi
done
[ "$found" -eq 0 ] && ok "не найдены"

# ---------------------------------------------------------------------------
# 2. Цвет в обход палитры
#
# Вписанные байтами escape-коды проходят мимо NO_COLOR и мимо снятия цвета без
# терминала. В прогоне без TTY такие строки остаются единственными крашеными, и
# коды лезут в вывод текстом — так и обнаружилось в блоке гео.
# ---------------------------------------------------------------------------
say "2. Цвет в обход палитры"
found=0
for f in vsm menus/*.sh; do
    n=$(grep -c '\\033\[' "$f" 2>/dev/null) || n=0
    if [ "${n:-0}" -gt 0 ]; then
        bad "$f: строк $n"
        grep -n '\\033\[' "$f" | sed 's/^/      /' | head -3
        found=1
    fi
done
[ "$found" -eq 0 ] && ok "не найдено"

# ---------------------------------------------------------------------------
# 3. Подпись не короче своей колонки
#
# Самый коварный из трёх. ui_pad дополняет строку ТОЛЬКО если она короче
# ширины: при равенстве дополнения нет вовсе, и значение печатается вплотную к
# подписи — «Виртуализацияkvm», «Учётные данныене записаны». Оба случая нашлись
# лишь в живом терминале, уже после коммита.
#
# Считаем длину литерала в символах и требуем запас хотя бы в один пробел.
# Значок внутри подписи считается за один символ — так же, как его считает сам
# ui_pad, поэтому проверка совпадает с поведением, а не с видом на экране.
# ---------------------------------------------------------------------------
say "3. Подпись помещается в свою колонку"
found=0
for f in "${FILES[@]}"; do
    while IFS= read -r hit; do
        line="${hit%%:*}"
        rest="${hit#*:}"
        # Разбираем ui_pad '<литерал>' <ширина>
        lit=$(sed -n "s/.*ui_pad '\([^']*\)' *\([0-9]\+\).*/\1/p" <<< "$rest")
        wid=$(sed -n "s/.*ui_pad '\([^']*\)' *\([0-9]\+\).*/\2/p" <<< "$rest")
        [ -n "$lit" ] && [ -n "$wid" ] || continue
        # Длину считаем так же, как её считает сам ui_pad, — через ${#s} при
        # UTF-8 локали. Через awk нельзя: на Ubuntu `awk` по умолчанию mawk, а
        # он не знает многобайтных символов даже при UTF-8 локали. Замерено на
        # стенде: «📦  Виртуализация» — mawk 32, gawk 16. То есть на обычном
        # сервере проверка ругалась бы на каждую кириллическую подпись.
        #
        # У меня она проходила потому, что на стенде в alternatives выбран
        # gawk, а локально свой awk. Проверка ни разу не запускалась в том
        # окружении, для которого написана, — ровно тот класс ошибки, который
        # она сама и должна ловить. Нашло облачное ревью.
        n=$(LC_ALL=C.UTF-8 bash -c 'echo ${#1}' -- "$lit")
        if [ "$n" -ge "$wid" ]; then
            bad "$f:$line подпись «$lit» — $n симв. при колонке $wid"
            found=1
        fi
    done < <(grep -n "ui_pad '" "$f" 2>/dev/null)
done
[ "$found" -eq 0 ] && ok "все подписи с запасом"

# ---------------------------------------------------------------------------
# 4. Клавиши идут по порядку
#
# При перегруппировке пунктов по смыслу легко оставить прежние клавиши — и на
# экране получается 1, 2, 5, 9, потом 3, 4, 6, 7. Читается как ошибка, и глазом
# нужный пункт уже не находится: человек ищет цифру, а она не там, где ждёт.
#
# Так и вышло в меню тестов и утилит после перегруппировки. Заметил владелец,
# а не проверка — потому что проверки на это не было.
# ---------------------------------------------------------------------------
# Счёт ведётся в пределах ЭКРАНА, а не файла: в одном файле их несколько, и
# нумерация в каждом своя. Границей считаем clear или ui_title — с них экран и
# начинается. Без этого проверка ругалась на первый же файл с двумя экранами.
# Один проход awk на файл, а не цикл по строкам с grep внутри.
#
# Первая редакция форкала два процесса на КАЖДУЮ строку девяти файлов, и вся
# проверка стала занимать две минуты вместо секунды. Проверку, которую положено
# гонять перед каждым коммитом, столько ждать никто не будет — а значит её
# перестанут запускать, и смысла в ней не останется.
say "4. Клавиши пунктов идут по возрастанию"
found=0
for f in vsm menus/*.sh; do
    while IFS= read -r hit; do
        [ -n "$hit" ] || continue
        bad "$hit"
        found=1
    done < <(awk -v fname="$f" '
        BEGIN { prev = -1 }
        # Границы экрана: его начало (clear, ui_title) И его конец — строка
        # чтения выбора.
        #
        # Одних clear/ui_title мало. Часть списков живёт прямо в обработчике —
        # «чем сканировать ncdu», «какой протокол для порта», «как убивать
        # процесс», — и никакого заголовка перед ними нет. Пока эти списки
        # рисовались вручную, проверка их не видела вовсе; после перевода на
        # ui_item она увидела их как продолжение внешнего меню и объявила
        # ошибкой возврат нумерации к единице. Ошибка была в модели, не в меню.
        /clear|ui_title/ { prev = -1; next }
        /read[[:space:]]+(-[a-z]+[[:space:]]+)*-p/ { prev = -1; next }
        match($0, /ui_(danger_)?item +"[0-9]+"/) {
            k = substr($0, RSTART, RLENGTH)
            gsub(/[^0-9]/, "", k)
            k = k + 0
            if (k <= prev) print fname ": клавиша " k " идёт после " prev
            prev = k
        }
    ' "$f")
done
[ "$found" -eq 0 ] && ok "порядок не нарушен"

# ---------------------------------------------------------------------------
# 5. Дрейф палитры — отчёт, а не отказ
#
# Сырые цвета остаются законными там, где цвет несёт смысл: предупреждение,
# ошибка, состояние службы. Запрещать их целиком значило бы переписать проверки
# состояний ради вида. Поэтому здесь счётчик: если в файле снова копятся
# десятки YELLOW и CYAN, это видно сразу, а решение остаётся за человеком.
# ---------------------------------------------------------------------------
say "5. Использование сырых цветов (отчёт)"
printf '  %-26s %6s %6s %6s %6s %6s\n' файл RED GREEN YELLOW BLUE CYAN
for f in vsm menus/*.sh; do
    printf '  %-26s' "$f"
    for c in RED GREEN YELLOW BLUE CYAN; do
        printf ' %6s' "$(grep -o "\${$c}" "$f" | wc -l)"
    done
    echo
done

# ---------------------------------------------------------------------------
# 6. Пункт меню, нарисованный мимо примитивов
#
# Слепое пятно всех проверок выше: они построены ОТ ui_item. Пункт, набранный
# руками через echo, для них не существует — а значит для него не работает
# ничего: ни выравнивание колонок, ни порядок клавиш, ни палитра.
#
# Так и было. Переделка оформления прошла по главным экранам, а сорок шесть
# пунктов во вложенных списках остались набраны вручную и разъехались: после
# эмодзи то один пробел, то три, подписи без описаний, выход то X, то 0.
# Нашёл это владелец глазами — второй раз по той же причине, что и в прошлый.
#
# Ищем начало строки-пункта: необязательный отступ, необязательная переменная
# цвета, один знак, скобка, пробел. Внутри обычных сообщений такое сочетание не
# встречается, а перечисления в подсказках начинаются с тире.
#
# Первая редакция этой проверки ТРЕБОВАЛА переменную цвета перед клавишей и
# потому ловила только половину — цветные пункты BBR нашла, а простые
# `echo "  1) ..."` в меню тестов пропустила. Проверка, которая ловит половину
# случаев, хуже отсутствующей: она создаёт уверенность. Отсюда правило для
# этого файла: у каждого нового образца проверять обе стороны — и что ловит,
# и что пропускает.
# ---------------------------------------------------------------------------
say "6. Пункты меню нарисованы примитивами, а не вручную"
found=0
UI_RAW_ITEM='^[[:space:]]*echo( -e)? +"[[:space:]]*([$][{][A-Z_]*[}])?[[:space:]]*[0-9Xx][)][[:space:]]'
for f in vsm menus/*.sh; do
    while IFS= read -r hit; do
        [ -n "$hit" ] || continue
        bad "$f:$(cut -c1-90 <<< "$hit")"
        found=1
    done < <(grep -nE "$UI_RAW_ITEM" "$f" 2>/dev/null)
done
[ "$found" -eq 0 ] && ok "все пункты через ui_item / ui_danger_item"

# ---------------------------------------------------------------------------
# 7. У ui_danger_item нет параметра эмодзи
#
# Сигнатуры соседних функций РАЗНЫЕ, и это ловушка:
#
#   ui_item        клавиша эмодзи подпись описание
#   ui_danger_item клавиша        подпись описание [ширина]
#
# Опасному пункту эмодзи не нужен — у него свой знак MARK_DANGER. Но рука
# пишет по образцу соседней строки, и лишний аргумент сдвигает ВСЁ: подпись
# становится эмодзи, описание — подписью, а описание уезжает в позицию
# ширины, где его ждёт арифметика.
#
# Поймано на себе: при переводе вложенных списков на примитивы я вписал эмодзи
# в пять вызовов из одиннадцати. Глазами такое не видно — экран рисуется, цифры
# на местах, просто колонка съезжает.
# ---------------------------------------------------------------------------
say "7. ui_danger_item вызывается без эмодзи"
found=0
for f in vsm menus/*.sh; do
    while IFS= read -r hit; do
        [ -n "$hit" ] || continue
        bad "$f:$(cut -c1-90 <<< "$hit")"
        found=1
    # Считаем аргументы, а не смотрим на их содержимое.
    #
    # Первая редакция искала «не-буква в начале второго аргумента» — и
    # объявляла дефектом ВСЕ правильные вызовы: кириллица не входит в
    # [:alnum:] в локали C, поэтому «Удалить» выглядело для неё эмодзи.
    # Проверка, ругающаяся на исправный код, живёт до первого прогона: её
    # выключают, а не чинят.
    #
    # Правило локале-независимое: у ui_danger_item допустимы три аргумента в
    # кавычках, четвёртым может быть только ширина — число. Всё остальное на
    # четвёртом месте означает сдвиг из-за лишнего эмодзи.
    done < <(awk -v q='"' '
        /ui_danger_item/ {
            n = split($0, a, q)
            # Кавычек: 2 на аргумент плюс хвост. Четыре аргумента дают n >= 9.
            if (n >= 9) {
                fourth = a[8]
                if (fourth !~ /^[0-9]+$/) print FNR ":" $0
            }
        }
    ' "$f" 2>/dev/null)
done
[ "$found" -eq 0 ] && ok "лишних аргументов нет"

echo
if [ "$FAIL" -eq 0 ]; then
    echo -e "\033[0;32mОформление: находок нет.\033[0m"
else
    echo -e "\033[0;31mОформление: есть находки, см. выше.\033[0m"
fi
exit "$FAIL"
