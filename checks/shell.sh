#!/bin/bash

# ======================================================================
# СТАТИЧЕСКИЙ РАЗБОР BASH-ЧАСТИ VSM
#
#   bash checks/shell.sh          замечания уровня warning, ноль или провал
#   bash checks/shell.sh --all    ещё и style: смотреть глазами, не чинить всё
#
# ЗАЧЕМ ПОРОГ ИМЕННО НОЛЬ. Проверка с накопленным долгом бесполезна: список из
# двух десятков «известных» замечаний никто не читает, и новое настоящее
# теряется среди них в первый же день. Поэтому всё, что признано неприменимым,
# разобрано и отключено в .shellcheckrc с объяснением, а остальное обязано быть
# исправлено.
#
# Уровень style сюда НЕ входит намеренно. Там 250 замечаний, и почти все —
# `read` без -r в пунктах меню, где ввод это цифра или домен. Единственное
# место, где читается пароль, уже сделано правильно: `IFS= read -rs`
# в menus/xui.sh. Править остальные значило бы менять двести строк ради отчёта.
# ======================================================================

set -uo pipefail

VSM_ROOT="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." && pwd)"
cd "$VSM_ROOT" || { echo "Не найден корень VSM" >&2; exit 2; }

if ! command -v shellcheck >/dev/null 2>&1; then
    echo "ShellCheck не установлен. Поставить: apt-get install -y shellcheck" >&2
    exit 2
fi

SEVERITY="warning"
[ "${1:-}" = "--all" ] && SEVERITY="style"

# Список файлов берём у git, а не маской: так в разбор не попадают ни venv, ни
# скачанные чужие установщики, ни резервные копии.
mapfile -t FILES < <(git ls-files '*.sh' vsm 2>/dev/null)
if [ "${#FILES[@]}" -eq 0 ]; then
    echo "Не нашёл ни одного скрипта — запускать из рабочей копии git." >&2
    exit 2
fi

echo
echo "СТАТИЧЕСКИЙ РАЗБОР BASH  (файлов: ${#FILES[@]}, уровень: $SEVERITY)"
echo "──────────────────────────────────────────────────────────────"

OUT="$(shellcheck -f gcc -S "$SEVERITY" -- "${FILES[@]}" 2>/dev/null)"
COUNT=0
[ -n "$OUT" ] && COUNT="$(printf '%s\n' "$OUT" | wc -l)"

# Синтаксис проверяем отдельно: shellcheck разбирает файл, но не заменяет
# `bash -n`, а сломанный скрипт обязан быть виден сразу.
SYNTAX_BAD=0
for f in "${FILES[@]}"; do
    bash -n "$f" 2>/dev/null || { echo "  СИНТАКСИС: $f"; SYNTAX_BAD=1; }
done

if [ "$COUNT" -gt 0 ]; then
    printf '%s\n' "$OUT" | sed 's/^/  /'
    echo "──────────────────────────────────────────────────────────────"
fi

if [ "$SEVERITY" = "style" ]; then
    echo "  Замечаний уровня style: $COUNT. Это справка, а не приговор."
    exit "$SYNTAX_BAD"
fi

if [ "$COUNT" -gt 0 ] || [ "$SYNTAX_BAD" -ne 0 ]; then
    echo "  Замечаний: $COUNT. Порог — ноль."
    echo "  Если замечание неприменимо, разберите его и внесите в .shellcheckrc"
    echo "  с объяснением — молча глушить в коде не нужно."
    exit 1
fi

echo "  Замечаний нет, синтаксис в порядке."
exit 0
