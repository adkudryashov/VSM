# Ожидание освобождения блокировки dpkg.
#
# VSM по назначению запускают на ТОЛЬКО ЧТО созданном VPS, а там первые минуты
# работает unattended-upgrades и держит /var/lib/dpkg/lock-frontend. Любой apt
# в этот момент возвращает ошибку, и пакет молча не ставится. Поймано на
# чистой Ubuntu 24.04: из-за этого не установился acl, а следом умер весь
# установщик стека.
#
# Ждём молча только первые пару секунд: если блокировка держится дольше,
# пользователь должен понимать, почему всё встало.
function wait_for_apt {
    local waited=0 limit="${1:-300}"
    while fuser /var/lib/dpkg/lock-frontend /var/lib/dpkg/lock \
                /var/lib/apt/lists/lock &>/dev/null; do
        if [ "$waited" -eq 0 ]; then
            echo -e "${YELLOW}    ожидаю освобождения apt (идёт установка обновлений)...${NC}"
        fi
        sleep 3
        waited=$((waited + 3))
        if [ "$waited" -ge "$limit" ]; then
            echo -e "${RED}    apt занят дольше ${limit} с — продолжаю без ожидания.${NC}"
            return 1
        fi
    done
    return 0
}

# Ставит пакеты и проверяет результат по факту.
#
# Раньше по всему меню повторялось `apt update && apt install -y ...`. Если в
# системе есть чужой битый репозиторий, `apt update` возвращает 100, `&&`
# обрывает цепочку, и пакеты молча не ставятся. `set -e` этого не ловит:
# первая команда AND-списка не последняя, её падение игнорируется. В итоге
# установка сообщала об успехе, а программы не было.
#
# Аргументы: имена пакетов. Если имя команды отличается от пакета,
# передавайте «пакет:команда» — проверяться будет команда.
function ensure_packages {
    local missing=() spec pkg cmd
    for spec in "$@"; do
        pkg="${spec%%:*}"; cmd="${spec##*:}"
        command -v "$cmd" &> /dev/null || missing+=("$pkg")
    done
    [ ${#missing[@]} -eq 0 ] && return 0

    echo -e "${YELLOW}>>> Требуется установить: ${missing[*]}${NC}"
    wait_for_apt
    # Обновление списков не через &&: его провал из-за чужого репозитория
    # не должен мешать установке пакетов из рабочих источников.
    sudo apt-get update -qq 2>/dev/null || \
        echo -e "${YELLOW}    (списки пакетов обновились с ошибками, продолжаю)${NC}"
    sudo DEBIAN_FRONTEND=noninteractive apt-get install -y "${missing[@]}" || true

    local failed=()
    for spec in "$@"; do
        pkg="${spec%%:*}"; cmd="${spec##*:}"
        command -v "$cmd" &> /dev/null || failed+=("$pkg")
    done
    if [ ${#failed[@]} -gt 0 ]; then
        echo -e "${RED}❌ Не удалось установить: ${failed[*]}${NC}"
        echo -e "${YELLOW}   Смотрите вывод apt выше — там причина.${NC}"
        # Битый сторонний репозиторий — частая, но не единственная причина.
        # Называем его только если он действительно есть, иначе подсказка
        # уводила бы от настоящей проблемы (нехватка места, конфликт версий).
        if ! sudo apt-get update -qq >/dev/null 2>&1; then
            echo -e "${YELLOW}   Списки пакетов обновляются с ошибками. Проверьте"
            echo -e "   сторонние репозитории:${NC}"
            sudo apt-get update 2>&1 >/dev/null | grep -iE "^(E|W|Ошб|Err)" | head -3 | sed 's/^/     /'
        fi
        return 1
    fi
    echo -e "${GREEN}✓ Установлено: ${missing[*]}${NC}"
    return 0
}

# Скачивает внешний скрипт и запускает его.
#
# Замена для `bash <(curl ...)` и `curl ... | bash`: там при неудачной загрузке
# bash получает пустой ввод и выходит с нулём — сбой выглядел как успешное
# выполнение. Здесь загрузка отделена от запуска, и пустой ответ считается
# ошибкой.
#
# Аргументы: URL, затем аргументы самого скрипта.
function run_remote_script {
    local url="$1"; shift
    local tmp; tmp=$(mktemp /tmp/vsm-remote.XXXXXX.sh) || return 1

    if ! curl -fsSL --max-time 60 "$url" -o "$tmp" || [ ! -s "$tmp" ]; then
        rm -f "$tmp"
        echo -e "${RED}❌ Не удалось загрузить скрипт:${NC}"
        echo -e "${YELLOW}   $url${NC}"
        echo -e "${YELLOW}   Проверьте подключение к интернету и повторите.${NC}"
        return 1
    fi

    bash "$tmp" "$@"
    local rc=$?
    rm -f "$tmp"
    return $rc
}

# Файл известных отпечатков сторонних скриптов: строки «<url> <sha256> <дата>».
# Не секрет — это публичные файлы, — поэтому обычные права.
UPSTREAM_FP_FILE="${UPSTREAM_FP_FILE:-/etc/vsm/upstream.sha256}"

# Сверяет отпечаток скачанного файла с запомненным.
#
# ЗАЧЕМ: всё стороннее тянется с ветки main без пиннинга и выполняется от root.
# Изменение у автора приезжает молча, при следующем же запуске. Так и вышло с
# 3x-ui-pro: автор удалил разбор -auto_domain, VSM продолжал его передавать, а
# установщик проглатывал неизвестный флаг веткой `*) shift 1` — ни ошибки, ни
# слова. Узнали не от кода.
#
# Решение владельца: запоминать отпечаток и предупреждать при изменении, версии
# НЕ фиксировать. Поэтому здесь нет ни отказа, ни пиннинга — только громкий
# рассказ о том, что файл стал другим.
#
# Возвращает 0, если отпечаток совпал или запомнен впервые, и 1, если разошёлся.
# Код возврата — сигнал вызывающему («покажи паузу»), а не запрет.
function upstream_fingerprint {
    local url="$1" file="$2"
    local now; now=$(date '+%F')
    local new; new=$(sha256sum "$file" 2>/dev/null | awk '{print $1}') || new=""
    if [ -z "$new" ]; then
        echo -e "${YELLOW}❗  Не удалось посчитать отпечаток ${url} — сверка пропущена.${NC}"
        return 0
    fi

    mkdir -p "$(dirname "$UPSTREAM_FP_FILE")" 2>/dev/null
    local old="" when=""
    if [ -f "$UPSTREAM_FP_FILE" ]; then
        # Читаем построчно, а не грепом по url: подстрока одного адреса может
        # встретиться внутри другого, и мы сверили бы файл не с тем отпечатком.
        local u h d
        while read -r u h d; do
            if [ "$u" = "$url" ]; then old="$h"; when="$d"; fi
        done < "$UPSTREAM_FP_FILE"
    fi

    if [ -z "$old" ]; then
        ( umask 077; printf '%s %s %s\n' "$url" "$new" "$now" >> "$UPSTREAM_FP_FILE" )
        echo -e "${BLUE}   Отпечаток запомнен: ${new:0:16}…${NC}"
        return 0
    fi

    if [ "$old" = "$new" ]; then
        return 0
    fi

    echo -e "\n${RED}❗  СТОРОННИЙ СКРИПТ ИЗМЕНИЛСЯ С ПРОШЛОГО ЗАПУСКА${NC}"
    echo -e "${YELLOW}   $url${NC}"
    echo -e "${YELLOW}   было  ${old}  (${when})${NC}"
    echo -e "${YELLOW}   стало ${new}  (${now})${NC}"
    echo -e "${YELLOW}   Файл выполняется от root. Автор мог сменить аргументы,${NC}"
    echo -e "${YELLOW}   и VSM продолжит передавать старые — молча.${NC}"

    # Запоминаем новый сразу: иначе предупреждение повторялось бы при каждом
    # запуске и очень быстро перестало бы читаться.
    local tmp; tmp=$(mktemp "${UPSTREAM_FP_FILE}.XXXXXX") || return 1
    if [ -f "$UPSTREAM_FP_FILE" ]; then
        # Сравнение поля целиком через awk, а не `grep -v "^$url "`: в адресе
        # есть точки и слэши, а для регулярки точка — любой символ. Похожий
        # адрес соседнего проекта вычистился бы заодно.
        awk -v u="$url" '$1 != u' "$UPSTREAM_FP_FILE" > "$tmp" 2>/dev/null || true
    fi
    printf '%s %s %s\n' "$url" "$new" "$now" >> "$tmp"
    chmod 600 "$tmp" 2>/dev/null
    mv "$tmp" "$UPSTREAM_FP_FILE"
    return 1
}

# Качает установщик 3x-ui-pro во временный файл и готовит его к запуску:
# сверяет отпечаток и снимает проверку CPU.
#
# Одна функция на все пути, потому что раньше проверка CPU снималась ТОЛЬКО
# при установке панели. Установка стека в режиме full и удаление панели
# запускают тот же файл без правки — и на хостерах с эмулированным процессором
# оба падали: одно на этапе 1, другое чужой английской ошибкой.
#
# Про саму проверку: check_cpu ищет «QEMU» в /proc/cpuinfo и делает exit 1.
# Апстрим считает это требованием ради скорости Xray — на эмулированном
# процессоре он медленнее. Это осознанный размен: без снятия панель на таких
# VPS не поставить вовсе. Файл у автора не трогаем, правка живёт в копии.
#
# Аргументы: URL, путь для сохранения. Возвращает 1, если скачать не удалось.
function xui_installer_fetch {
    local url="$1" out="$2"
    # Сбрасываем на КАЖДОМ вызове: без сброса флаг, поднятый прошлой загрузкой,
    # заставил бы следующую показывать паузу про изменение, которого не было.
    UPSTREAM_CHANGED=0

    if ! curl -fsSL --max-time 60 "$url" -o "$out" || [ ! -s "$out" ]; then
        rm -f "$out"
        echo -e "${RED}❌ Не удалось загрузить ${url}${NC}"
        echo -e "${YELLOW}   Проверьте подключение к интернету и повторите.${NC}"
        return 1
    fi

    upstream_fingerprint "$url" "$out" || UPSTREAM_CHANGED=1

    # Снятие проверяем ФАКТОМ, а не совпадением якоря. Прежний код правил файл
    # только при `grep -q '^check_cpu$'`, а при несовпадении молчал и ехал
    # дальше — падать уже у автора. Достаточно смены отступа или `check_cpu ||
    # true`, чтобы мы узнали об этом лишь на QEMU-хостере.
    sed -i 's/^[[:space:]]*check_cpu[[:space:]]*$/: # проверка CPU снята VSM/' "$out"
    local left
    left=$(grep -cE '^[[:space:]]*check_cpu([[:space:]]|$)' "$out" 2>/dev/null) || left=0
    if [ "${left:-0}" -ne 0 ]; then
        echo -e "${YELLOW}❗  Проверка CPU снята не полностью: осталось вызовов — ${left}.${NC}"
        echo -e "${YELLOW}   На хостере с эмулированным QEMU-процессором установщик${NC}"
        echo -e "${YELLOW}   оборвётся. Вызов у автора изменился — нужен новый шаблон.${NC}"
    fi
    return 0
}

function check_and_install_qrencode {
    if ! command -v qrencode &> /dev/null; then
        echo -e "${YELLOW}💡 Утилита 'qrencode' не найдена.${NC}"
        read -p "$(echo -e "${YELLOW}Установить qrencode для отображения QR-кода? [Y/n]: ${NC}")" INSTALL_QR
        
        if [[ "$INSTALL_QR" =~ ^[Yy]$ || -z "$INSTALL_QR" ]]; then
            echo -e "${CYAN}>>> Запуск установки qrencode...${NC}"
            if command -v apt &> /dev/null; then
                sudo apt update -y > /dev/null 2>&1
                sudo apt install qrencode -y
            elif command -v yum &> /dev/null; then
                sudo yum install qrencode -y
            elif command -v dnf &> /dev/null; then
                sudo dnf install qrencode -y
            else
                echo -e "${RED}❌ Не удалось найти подходящий менеджер пакетов (apt, yum, dnf). Установите qrencode вручную.${NC}"
                return 1
            fi
            
            if command -v qrencode &> /dev/null; then
                echo -e "${GREEN}✅ qrencode успешно установлен.${NC}"
                return 0 # Установка успешна
            else
                echo -e "${RED}❌ Установка qrencode завершилась неудачей.${NC}"
                return 1
            fi
        fi
        return 1 # Пользователь отказался или установка не удалась
    fi
    return 0 # Уже установлен
}
