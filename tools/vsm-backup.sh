#!/bin/bash

# ======================================================================
# РЕЗЕРВНАЯ КОПИЯ НЕВОСПРОИЗВОДИМОГО
#
#   bash tools/vsm-backup.sh              создать копию
#   bash tools/vsm-backup.sh --list       показать имеющиеся
#   bash tools/vsm-backup.sh --restore <файл>   вернуть из копии
#
# ЧТО ЗДЕСЬ ХРАНИТСЯ И ПОЧЕМУ ЭТО ВАЖНО. Двадцать килобайт, которые нельзя
# восстановить ниоткуда:
#
#   TELEMT_SECRET       секрет прокси. Его знают ВСЕ клиенты. Потерять его —
#                       значит выдать всем новые ссылки заново, потому что
#                       подключение отвалится разом и у всех.
#   PANEL_PREFIX        секретный путь панели, на котором держится её
#                       незаметность.
#   учётки панелей      3x-ui хранит пароль bcrypt-хэшем и наружу не отдаёт;
#                       VSM их не добывает, а ЗАПОМИНАЕТ (см. lib/config.sh).
#                       Забыли — восстановить неоткуда.
#   bot_monitor.db      токены доступа к чужим панелям 3x-ui.
#   xui/                снимок 3x-ui: база с клиентами и ключами плюс всё,
#                       куда установщик вписал её порты и пути. Сотни
#                       килобайт. Возвращается tools/xui-restore.sh.
#
# ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. ip_history.db — данные, которые набегают сами за
# сутки работы. GeoIP — 83 МБ, скачиваются заново. venv — ставится из
# requirements.txt. Резервная копия должна быть маленькой настолько, чтобы её
# не ленились унести с сервера.
#
# ГЛАВНОЕ ОГРАНИЧЕНИЕ, О КОТОРОМ НЕЛЬЗЯ МОЛЧАТЬ. Копия лежит на ТОМ ЖЕ ДИСКЕ.
# Она спасает от случайного удаления, неудачной правки, переустановки и
# сломавшейся автопочинки — но НЕ от гибели диска и не от потери сервера.
# Против этого помогает только одно: унести архив наружу. Скрипт печатает
# готовую команду при каждом создании копии, потому что резервная копия, о
# которой вспоминают после аварии, ничего не стоит.
# ======================================================================

set -uo pipefail

VSM_ROOT="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.." && pwd)"
BACKUP_DIR="${VSM_BACKUP_DIR:-/var/backups/vsm/config}"
KEEP="${VSM_BACKUP_KEEP:-14}"

# Пути внутри архива хранятся относительными: так восстановление не зависит от
# того, где лежит VSM, и распаковка не может перезаписать что-то мимо цели.
ETC_DIR="/etc/vsm"
BOTS_DIR="$VSM_ROOT/bots"

RED=$'\e[1;31m'; GREEN=$'\e[1;32m'; YELLOW=$'\e[1;33m'; NC=$'\e[0m'
say()  { printf '%s\n' "$*"; }
warn() { printf '%s%s%s\n' "$YELLOW" "$*" "$NC" >&2; }
die()  { printf '%s%s%s\n' "$RED" "$*" "$NC" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "Нужен root: файлы имеют права 600 и принадлежат ему."

# ----------------------------------------------------------------------
list_backups() {
    if [ ! -d "$BACKUP_DIR" ] || [ -z "$(ls -A "$BACKUP_DIR" 2>/dev/null)" ]; then
        say "Копий пока нет. Создать: bash tools/vsm-backup.sh"
        return 0
    fi
    say "Копии в $BACKUP_DIR:"
    # find вместо ls: имена свои, но привычка одна на весь проект.
    find "$BACKUP_DIR" -maxdepth 1 -name 'config-*.tar.gz' -printf '%TY-%Tm-%Td %TH:%TM  %6s б  %p\n' \
        | sort -r
}

# ----------------------------------------------------------------------
# Снимок 3x-ui: то, без чего переустановленная панель не станет прежней.
#
# Клиенты, их ключи и ссылки живут в базе панели. Но база одна ничего не
# вернёт: установщик 3x-ui-pro генерирует случайные порты и пути (ws, grpc,
# xhttp, подписка, панель, диагностика, mtr-backend) и вписывает их не только
# в базу, но и в nginx, в шаблон Clash-подписки, в страницу диагностики и в
# юнит mtr-backend. Вернуть базу без них — значит развести пути: ссылки
# клиентов указывают на старые, nginx слушает новые.
#
# Поэтому снимок согласованный: база плюс всё, куда вписаны её пути.
#
# ПОЧЕМУ НЕ СКРИПТ АВТОРА (x-ui-backup). Он делает то же, но целиком: замер на
# новом сервере 24.09.2026 — 1,4 ГБ, из них 1,1 ГБ файлы проверки скорости и
# 260 МБ бинарники. Такое в суточную копию не кладут и с сервера не уносят. И
# на время снятия он останавливает панель, то есть рвёт VPN у всех клиентов.
# Здесь база снимается механизмом резервного копирования SQLite на ходу, а
# бинарники и данные поставит установщик — снимок весит сотни килобайт.
#
# Возвращает снимок tools/xui-restore.sh, а не --restore ниже: он переписывает
# nginx и базу работающей панели, и делать это заодно с секретами нельзя.
xui_snapshot() {
    # Пути переопределяются только проверками: tests/test_xui_restore.py
    # снимает снимок с поддельных каталогов, а не с живой панели.
    local stage="$1/xui" db="${XUI_DB:-/etc/x-ui/x-ui.db}"
    local nginx="${NGINX_DIR:-/etc/nginx}" www="${WWW_DIR:-/var/www}"
    local units="${UNIT_DIR:-/etc/systemd/system}"
    [ -f "$db" ] || return 1
    command -v python3 >/dev/null 2>&1 || { warn "  снимок 3x-ui пропущен: нет python3"; return 1; }
    mkdir -p "$stage/www" || return 1
    # База в режиме WAL: свежие записи лежат в x-ui.db-wal, и копия одного
    # файла их потеряла бы. Механизм резервного копирования SQLite забирает всё.
    python3 - "$db" "$stage/x-ui.db" <<'PY' || { warn "  снимок базы 3x-ui не удался"; return 1; }
import sqlite3, sys
src = sqlite3.connect(sys.argv[1])
dst = sqlite3.connect(sys.argv[2])
src.backup(dst)
dst.close()
src.close()
PY
    [ -d "$nginx" ] && cp -a "$nginx" "$stage/nginx"
    [ -d "$www/subpage" ] && cp -a "$www/subpage" "$stage/www/subpage"
    # Из диагностики — только страница: в ней вписан её путь. Остальное там —
    # гигабайт файлов проверки скорости, его поставит установщик.
    local d
    for d in diagnostics html; do
        [ -f "$www/$d/index.html" ] || continue
        mkdir -p "$stage/www/$d"
        cp -a "$www/$d/index.html" "$stage/www/$d/"
    done
    [ -f "$units/mtr-backend.service" ] \
        && cp -a "$units/mtr-backend.service" "$stage/mtr-backend.service"
    return 0
}

create_backup() {
    mkdir -p "$BACKUP_DIR" || die "Не создать $BACKUP_DIR"
    chmod 700 "$(dirname "$BACKUP_DIR")" 2>/dev/null
    chmod 700 "$BACKUP_DIR"

    local stamp archive n
    stamp="$(date '+%Y-%m-%d-%H%M%S')"
    archive="$BACKUP_DIR/config-${stamp}.tar.gz"

    # Имя с точностью до секунды — и этого оказалось мало.
    #
    # Восстановление сначала сохраняет текущее состояние, и если оно уложилось
    # в ту же секунду, что и архив-источник, копия ПЕРЕЗАПИСЫВАЛА ровно тот
    # файл, из которого шло восстановление. То есть операция уничтожала свой
    # собственный источник, а отчитывалась об успехе: проверка наличия файлов
    # честно находила их в подменённом архиве. Поймано на стенде тем, что
    # после восстановления сверялись отпечатки.
    n=1
    while [ -e "$archive" ]; do
        archive="$BACKUP_DIR/config-${stamp}-${n}.tar.gz"
        n=$((n + 1))
        [ "$n" -gt 100 ] && die "Слишком много копий за одну секунду — что-то не так."
    done

    # Собираем список того, что реально существует: на установке без ботов нет
    # .env, без панели — нет её конфига. Просить tar заархивировать отсутствующее значит
    # получить ненулевой код возврата и решить, что копия не удалась.
    local -a items=()
    [ -d "$ETC_DIR" ]                    && items+=("-C" "/" "etc/vsm")
    # Конфиг движка. ЕГО ЗДЕСЬ НЕ БЫЛО, и это была главная дыра копии.
    #
    # В /etc/telemt/telemt.toml лежит ядро незаметности — mask, mask_host,
    # mask_port, tls_domain, — и секреты пользователей в [access.users]. То
    # есть ровно то, ради чего копия и заводилась: потеряв сервер, без этого
    # файла восстанавливать нечего, а ссылки всех клиентов обрываются.
    #
    # Пропущено было незаметно: копия исправно собиралась, проверялась
    # разворачиванием и содержала /etc/vsm — то есть выглядела полной. Найдено
    # на приёмке 27.08.2026 случайно, при разборе совсем другого вопроса.
    [ -f /etc/telemt/telemt.toml ]       && items+=("-C" "/" "etc/telemt/telemt.toml")
    # Конфиг веб-панели MTProxyL: адрес, секретный путь и хэш пароля. Панель
    # чужая, но путь к ней — наш секрет, и заново его знать неоткуда.
    [ -f /etc/mtproxyl-panel/config.toml ] && items+=("-C" "/" "etc/mtproxyl-panel/config.toml")
    [ -f "$BOTS_DIR/.env" ]              && items+=("-C" "$VSM_ROOT" "bots/.env")
    [ -f "$BOTS_DIR/data/bot_monitor.db" ] && items+=("-C" "$VSM_ROOT" "bots/data/bot_monitor.db")

    # Снимок 3x-ui — во временный каталог рядом с копиями (700, только root):
    # внутри база панели с ключами всех клиентов.
    local stage=""
    stage="$(mktemp -d "$BACKUP_DIR/.xui-stage.XXXXXX")" || stage=""
    if [ -n "$stage" ] && xui_snapshot "$stage"; then
        items+=("-C" "$stage" "xui")
    fi

    [ "${#items[@]}" -gt 0 ] || { [ -n "$stage" ] && rm -rf "$stage"; die "Нечего сохранять: не найдено ни $ETC_DIR, ни bots/.env."; }

    # umask до создания: архив содержит секреты и не должен ни на мгновение
    # оказаться доступным всем. chmod после создания оставил бы такое окно.
    ( umask 077; tar -czf "$archive" "${items[@]}" 2>/dev/null ) \
        || { rm -f "$archive"; [ -n "$stage" ] && rm -rf "$stage"; die "Архив не создан."; }
    [ -n "$stage" ] && rm -rf "$stage"

    # Проверяем ФАКТОМ, а не кодом возврата tar: архив, который не читается
    # обратно, — это не резервная копия, а её видимость. Узнать об этом в день
    # аварии слишком поздно.
    local count
    count="$(tar -tzf "$archive" 2>/dev/null | wc -l)"
    if [ "${count:-0}" -lt 1 ]; then
        rm -f "$archive"
        die "Архив создался, но не читается обратно — копия не сохранена."
    fi

    say "${GREEN}✓ Копия создана:${NC} $archive"
    say "  файлов внутри: $count, размер: $(stat -c %s "$archive") б, права: $(stat -c %a "$archive")"

    rotate

    # Печатаем ВСЕГДА, а не один раз при установке: копия на том же диске от
    # его гибели не спасает, и напоминать об этом надо в момент, когда человек
    # смотрит на результат.
    say ""
    warn "Эта копия лежит на том же диске, что и оригинал."
    warn "От потери диска спасёт только вынос наружу. С вашей машины:"
    # Адрес берём ТОТ, ПО КОТОРОМУ ДО СЕРВЕРА ДОХОДЯТ, а не hostname.
    #
    # Раньше здесь стоял `hostname -f`. Он печатает имя, под которым сервер
    # знает сам себя, — снаружи оно обычно не резолвится вовсе, и подсказка
    # выдавала команду, которая падает с «Could not resolve hostname». Поймано
    # владельцем: он скопировал её и получил именно этот отказ.
    #
    # ip route get локален и сети не трогает: спрашиваем ядро, с какого адреса
    # оно пойдёт наружу.
    local host
    host="$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for (i = 1; i < NF; i++) if ($i == "src") { print $(i + 1); exit }}')"
    say  "  scp ${host:-<адрес-сервера>}:${archive} ."
}

rotate() {
    local -a old
    mapfile -t old < <(find "$BACKUP_DIR" -maxdepth 1 -name 'config-*.tar.gz' -printf '%T@ %p\n' \
        | sort -rn | tail -n "+$((KEEP + 1))" | cut -d' ' -f2-)
    [ "${#old[@]}" -gt 0 ] || return 0
    rm -f -- "${old[@]}"
    say "  старых копий удалено: ${#old[@]} (храним последние $KEEP)"
}

# Распаковка одной ветки архива с проверкой ФАКТОМ.
#
# Первая версия просила tar достать член с именем "bots". Такого члена в
# архиве нет — есть "bots/.env" и "bots/data/bot_monitor.db", а каталог
# отдельной записью не сохранён. GNU tar в этом случае не находит совпадений,
# НИЧЕГО не распаковывает и выходит с НУЛЁМ. Скрипт бодро печатал
# «✓ Восстановлено», а .env оставался испорченным.
#
# Поймано на стенде тем, что после восстановления сверялись отпечатки файлов.
# Отсюда правило, третий раз за проект: код возврата — не доказательство.
# Здесь после распаковки проверяется наличие КАЖДОГО файла ветки.
#
# Аргументы: архив, префикс внутри архива, каталог назначения.
extract_branch() {
    local archive="$1" prefix="$2" dest="$3"
    local members missing=0 f

    members="$(tar -tzf "$archive" 2>/dev/null | grep "^${prefix}" | grep -v '/$')"
    # Ветки в архиве нет — это не ошибка: на установке без ботов нет bots/.
    [ -n "$members" ] || return 0

    tar -xzf "$archive" -C "$dest" --same-permissions --wildcards "${prefix}*" 2>/dev/null

    while IFS= read -r f; do
        [ -n "$f" ] || continue
        if [ ! -e "$dest/$f" ]; then
            warn "  не восстановлен: $dest/$f"
            missing=$((missing + 1))
        fi
    done <<< "$members"

    if [ "$missing" -gt 0 ]; then
        warn "Ветка ${prefix}: не восстановлено файлов — $missing"
        return 1
    fi
    say "  ветка ${prefix}: восстановлено файлов — $(printf '%s\n' "$members" | wc -l)"
    return 0
}

# ----------------------------------------------------------------------
restore_backup() {
    local archive="$1"
    [ -f "$archive" ] || die "Не найден архив: $archive"
    tar -tzf "$archive" >/dev/null 2>&1 || die "Архив не читается: $archive"

    say "В архиве:"
    tar -tzf "$archive" | sed 's/^/  /'
    say ""
    warn "ВОССТАНОВЛЕНИЕ ПЕРЕЗАПИШЕТ действующие секреты и учётные данные."
    warn "Если текущий TELEMT_SECRET отличается от сохранённого, после"
    warn "восстановления конфига и перезапуска telemt подключение отвалится"
    warn "у всех клиентов, чьи ссылки выданы с текущим секретом."
    say ""
    # Имя переменной латиницей: bash не принимает кириллицу в идентификаторах,
    # и `read ... ответ` рушит присваивание молча — подтверждение прошло бы
    # всегда. Ровно на этом уже обожглись в tools/heartbeat-check.sh.
    local answer
    read -r -p "Введите БОЛЬШИМИ буквами ДА для продолжения: " answer
    [ "$answer" = "ДА" ] || { say "Отменено."; exit 0; }

    # Источник уводим в снимок ДО всего остального.
    #
    # Дальше мы сохраняем текущее состояние в тот же каталог, и однажды это
    # уже перезаписало архив-источник (см. пояснение в create_backup). Даже с
    # починенным именованием полагаться на то, что два файла не столкнутся,
    # незачем: работаем со снимком, который никто снаружи тронуть не может.
    #
    # Снимок кладём в BACKUP_DIR (права 700, только root), а НЕ в /tmp: внутри
    # секрет прокси и пароли панели, а /tmp виден всем. Первая версия писала
    # именно в /tmp и вдобавок снимала файл ловушкой на EXIT, которая
    # ссылалась на ЛОКАЛЬНУЮ переменную — к моменту срабатывания её уже не
    # существовало, и архив с секретами оставался лежать в общем каталоге.
    # Убираем явно, в конце функции, без ловушек.
    mkdir -p "$BACKUP_DIR" && chmod 700 "$BACKUP_DIR"
    local snapshot="$BACKUP_DIR/.restore-source.tar.gz"
    ( umask 077; cp -- "$archive" "$snapshot" ) || die "Не скопировать архив."
    archive="$snapshot"

    # Перед перезаписью — копия того, что есть сейчас. Иначе восстановление
    # «не той» копии уничтожает действующие секреты без возврата.
    say "Сначала сохраняю текущее состояние…"
    create_backup >/dev/null 2>&1 && say "  текущее сохранено" || warn "  текущее сохранить не удалось"

    # Распаковываем ПОРОЗНЬ и только нужные ветки. Внутри архива два разных
    # основания: etc/vsm отсчитывается от корня файловой системы, а bots/ — от
    # корня репозитория. Одна общая распаковка в / положила бы .env в /bots,
    # то есть мимо цели и молча.
    local failed=0
    extract_branch "$archive" "etc/vsm" "/"        || failed=1
    # Ветки чужих конфигов. Их может не быть в старых архивах — extract_branch
    # это переживает: отсутствие ветки не ошибка, ошибка это ветка, которая не
    # распаковалась.
    extract_branch "$archive" "etc/telemt/" "/"    || failed=1
    extract_branch "$archive" "etc/mtproxyl-panel/" "/" || failed=1
    extract_branch "$archive" "bots/"  "$VSM_ROOT" || failed=1

    # Снимок убираем в любом исходе: в нём секреты, и лежать он не должен.
    rm -f "$snapshot"

    [ "$failed" -eq 0 ] || die "Восстановление НЕ завершено — смотрите сообщения выше."

    say "${GREEN}✓ Восстановлено, наличие каждого файла проверено.${NC}"
    say "Дальше перезапустите то, что читает эти файлы:"
    say "  systemctl restart telemt 3xui-telemt-bot"
    # Снимок 3x-ui здесь намеренно не трогаем — см. xui_snapshot.
    # Не конвейером в grep -q: при pipefail tar получает SIGPIPE, и условие
    # ложно при снимке на месте (см. tools/xui-restore.sh).
    local listing
    listing="$(tar -tzf "$1" 2>/dev/null)"
    if grep -qx 'xui/x-ui.db' <<< "$listing"; then
        say ""
        say "В архиве есть снимок 3x-ui (клиенты, ключи, пути). Он возвращается"
        say "отдельно, на установленную панель с теми же доменами:"
        say "  bash $VSM_ROOT/tools/xui-restore.sh $1"
        say "или при установке стека — установщик предложит сам."
    fi
}

# ----------------------------------------------------------------------
case "${1:-}" in
    --list)    list_backups ;;
    --restore) [ -n "${2:-}" ] || die "Укажите файл: --restore <путь>"; restore_backup "$2" ;;
    -h|--help) sed -n '3,40p' "$(readlink -f "${BASH_SOURCE[0]}")" ;;
    "")        create_backup ;;
    *)         die "Неизвестный аргумент: $1. Смотрите --help." ;;
esac
