"""
Разбор отчёта сверки с реестром решений VSM.

Сам реестр живёт в bash (lib/expectations.sh), сюда приезжает только его JSON.
Проверяются две чистые функции, от которых зависит, что увидит владелец:

split   — делит позиции на «уже вернули» и «ждёт вашего решения». Ошибка здесь
          означает либо молчание о том, что за человека поменяли настройку,
          либо тревогу о том, что уже починено.
signature — отличает «появилось новое расхождение» от «висит то же самое».
          Ошибка здесь означает либо шквал одинаковых сообщений раз в час,
          либо молчание о новой поломке, потому что она сочлась старой.
"""
import pytest

from telemt.watchdog import drift


def _позиция(id_, status, **прочее):
    return dict({"id": id_, "status": status, "class": "fix", "title": id_,
                 "why": "", "actual": "", "want": ""}, **прочее)


# --- split ----------------------------------------------------------------

def test_чинёное_и_ждущее_разъезжаются_по_спискам():
    отчёт = {"items": [
        _позиция("panel_listen", "починено"),
        _позиция("nginx_blocks", "расхождение"),
        _позиция("telemt_mask", "починить не удалось"),
    ]}
    чинёное, ждущее = drift.split(отчёт)
    assert [i["id"] for i in чинёное] == ["panel_listen"]
    assert [i["id"] for i in ждущее] == ["nginx_blocks", "telemt_mask"]


@pytest.mark.parametrize("статус", ["нет компонента", "исключено", "запомнено", "в порядке"])
def test_объяснения_почему_события_не_было_не_события(статус):
    """
    Эти четыре статуса не попадают НИ В ОДИН список: это не происшествия, а
    объяснения, почему происшествия нет. Попади они в ждущее — владелец
    получал бы раз в час письмо о том, что MTProxyL у него не установлен.
    """
    чинёное, ждущее = drift.split({"items": [_позиция("что-то", статус)]})
    assert чинёное == []
    assert ждущее == []


@pytest.mark.parametrize("отчёт", [None, {}, {"items": None}, {"items": []}])
def test_пустой_отчёт_не_роняет(отчёт):
    assert drift.split(отчёт) == ([], [])


# --- signature ------------------------------------------------------------

def test_один_и_тот_же_набор_даёт_один_отпечаток():
    а = [_позиция("nginx_blocks", "расхождение"), _позиция("panel_prefix", "расхождение")]
    б = [_позиция("panel_prefix", "расхождение"), _позиция("nginx_blocks", "расхождение")]
    assert drift.signature(а) == drift.signature(б), "порядок не должен влиять"


def test_новая_позиция_меняет_отпечаток():
    было = [_позиция("nginx_blocks", "расхождение")]
    стало = было + [_позиция("panel_prefix", "расхождение")]
    assert drift.signature(было) != drift.signature(стало)


def test_смена_статуса_той_же_позиции_меняет_отпечаток():
    """
    «Расхождение» и «починить не удалось» — разные новости об одной позиции.
    Считать их одним состоянием значило бы промолчать о том, что автопочинка
    перестала справляться.
    """
    а = [_позиция("telemt_mask", "расхождение")]
    б = [_позиция("telemt_mask", "починить не удалось")]
    assert drift.signature(а) != drift.signature(б)


def test_пустому_набору_соответствует_пустой_отпечаток():
    """Обнуление нужно, чтобы следующее такое же расхождение сообщилось как
    новое, а не утонуло в сравнении с прошлым."""
    assert drift.signature([]) == ""
