"""
Мост к двум прогонам, написанным до перехода на pytest.

check_watchdog.py (72 проверки логики сторожа) и check_auth.py (5 проверок
доступа) работают на своём мини-каркасе: печатают строки и считают провалы.
Каркас появился раньше pytest в этом проекте и пережил уже одну сессию.

ПОЧЕМУ ОБЁРТКА, А НЕ ПЕРЕПИСЫВАНИЕ. Переписывание 77 работающих проверок —
механическая правка с ненулевым риском потерять одну по дороге, а выигрыш
только в оформлении. Обёртка даёт то, ради чего это делалось: одна команда
`pytest` прогоняет ВСЁ, и ни один прогон не забудется. Что теряется: при
провале pytest покажет «упал один тест», а какая именно проверка не прошла —
видно в перехваченном выводе, он печатается тут же.

Переписать по-настоящему стоит, когда до этих файлов в следующий раз дойдут
руки по делу, а не ради галочки.
"""
import subprocess
import sys
from pathlib import Path

import pytest

TESTS = Path(__file__).resolve().parent
ROOT = TESTS.parent


@pytest.mark.parametrize("имя", ["check_watchdog.py", "check_auth.py"])
def test_прежний_прогон(имя):
    файл = TESTS / имя
    assert файл.is_file(), f"{имя} пропал из репозитория"
    # Отдельным процессом: оба файла правят глобальное состояние (ADMIN_IDS,
    # настройки) и в общем со всеми интерпретаторе мешали бы соседям.
    готово = subprocess.run(
        [sys.executable, str(файл)],
        cwd=str(ROOT), capture_output=True, text=True, timeout=120,
    )
    if готово.returncode != 0:
        pytest.fail(f"{имя} не прошёл:\n{готово.stdout}\n{готово.stderr}")
