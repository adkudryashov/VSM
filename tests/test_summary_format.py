"""
Значки и строка версии в сводке.

ЗАЧЕМ ЭТО ПОКРЫВАТЬ. Обе функции решают, ЧТО человек увидит первым, и
ошибаются молча: неверный порог не роняет бота, не пишет в журнал и не мешает
сообщению уйти. Заметить можно только глазами — и только если знать, каким
цвет должен был быть.

Значок качества особенно: до этой правки 🟢 и 🔴 стояли подписями строк
«Успешных» и «Сбои», то есть были украшением. Зелёный горел и при сорока
процентах успеха, красный светил при нуле сбоев. Значок обязан что-то
означать, иначе он мешает искать глазами тот, который означает.
"""

from telemt.utils.helpers import format_period
from telemt.handlers.common import BAD, OK, WARN, _quality_mark, _version_line


def test_версия_актуальная():
    assert _version_line("1.2.3", "1.2.3") == f"{OK} v1.2.3 · актуальная"


def test_версия_есть_обновление():
    assert _version_line("1.2.3", "1.3.0") == f"{WARN} v1.2.3 → v1.3.0"


def test_версия_апстрим_не_ответил():
    """
    Пустой latest — это «не удалось спросить», а не «есть обновление».
    Жёлтый в таком случае врал бы: мы не знаем, есть ли что обновлять.
    """
    assert _version_line("1.2.3", "") == f"{OK} v1.2.3 · актуальная"
    assert _version_line("1.2.3", None) == f"{OK} v1.2.3 · актуальная"


def test_качество_по_порогам():
    assert _quality_mark(100) == OK
    assert _quality_mark(99) == OK
    assert _quality_mark(98.9) == WARN
    assert _quality_mark(95) == WARN
    assert _quality_mark(94.9) == BAD
    assert _quality_mark(0) == BAD


def test_контроль_значок_не_постоянный():
    """
    Обратная сторона проверки выше: убедиться, что функция вообще способна
    вернуть разное. Без этого «порог 100 даёт зелёный» прошло бы и у функции,
    возвращающей зелёный всегда, — ровно тем дефектом, который чинили.
    """
    assert len({_quality_mark(100), _quality_mark(97), _quality_mark(10)}) == 3


# --- ФОРМАТ ПЕРИОДА ---------------------------------------------------
#
# В базе время ISO с поясом. Печатать его как есть нельзя: строка длинная,
# время чужое (UTC при сервере в другом поясе), читается по складам. Владелец
# указал на это, увидев экран очистки.

def test_период_за_один_день_пишет_дату_однажды():
    got = format_period("2026-08-28T04:17+00:00", "2026-08-28T05:43+00:00")
    assert "—" in got and got.count(".") == 1


def test_период_из_одной_точки_без_тире():
    """Диапазон из точки в ту же точку выглядит как ошибка."""
    got = format_period("2026-08-28T04:17+00:00", "2026-08-28T04:17+00:00")
    assert "—" not in got


def test_период_из_мусора_пуст():
    """Обратная сторона: неразобранное не должно печататься как есть."""
    assert format_period("не дата", "тоже нет") == ""
    assert format_period(None, None) == ""


# --- СОЕДИНЕНИЯ, НЕ СТАВШИЕ КЛИЕНТАМИ --------------------------------
#
# Эта строка один раз уже соврала: она называла их сканерами, хотя счётчик
# намерения не различает. Разбор 28.08.2026 показал, что 93% числа ничем не
# подтверждено, а часть его создают наши же зонды доступности. Формулировку
# исправили — тесты держат её, чтобы прежнее утверждение не вернулось.

from telemt.handlers.common import STRAY_RATE_HIGH, _stray_line
from telemt.watchdog.mtproxyl import own_probes_per_hour

СУТКИ = 86400.0
СМЕНА = 39684.0  # аптайм telemt в момент замера на стенде, 11 часов 1 минута


def test_ничего_не_показываем_когда_нечего():
    assert _stray_line(0, СМЕНА) == ""
    assert _stray_line(0, 0) == ""


def test_строка_не_называет_их_сканерами():
    """
    Главное, ради чего всё правилось. Счётчик считает всех, кто не подошёл, —
    контрольный случай на стенде поднял его обычным openssl s_client.
    """
    got = _stray_line(13754, СМЕНА)
    assert "Не стали клиентами" in got
    assert "сканер" not in got.lower()


def test_скорость_считается_и_показывается():
    """Ровный случай: 2400 за сутки — это сотня в час."""
    got = _stray_line(2400, СУТКИ)
    assert "100/час" in got


def test_всплеск_помечен_жёлтым():
    """Замер со стенда: 13 754 за 11 часов — это 1.2k в час."""
    got = _stray_line(13754, СМЕНА)
    assert got.startswith(WARN)
    assert "1.2k/час" in got
    # Крупное число обязано объяснить, почему оно никого не пугает: молчаливое
    # исключение из оценки — та самая дыра, ради которой всё правилось.
    assert "вне оценки" in got


def test_спокойный_фон_не_помечен():
    """
    Обратная сторона: без этого проверка выше прошла бы и у функции, которая
    жалуется всегда. 710 за те же 11 часов — 64 в час, обычный фон.
    """
    got = _stray_line(710, СМЕНА)
    assert got.startswith("🔍")
    assert "64/час" in got


def test_порог_разделяет_фон_и_всплеск():
    """Порог взят из замера; проверяем, что он и правда посередине."""
    час = 3600.0
    assert not _stray_line(int(STRAY_RATE_HIGH) - 1, час).startswith(WARN)
    assert _stray_line(int(STRAY_RATE_HIGH) + 1, час).startswith(WARN)


def test_строка_умещается_в_одну():
    """
    Владелец увидел первую редакцию в Telegram и сказал «длинная»: она занимала
    две строки. Длинная строка в сводке хуже неполной — её перестают читать
    целиком, и тогда не работает ни одна её часть.

    Порог 60 — по ширине, на которой сообщение переносилось на снимке экрана.
    Проверяются обе обстановки, потому что подробности в них разные.
    """
    for got in (_stray_line(13754, СМЕНА, own_per_hour=40.0),
                _stray_line(710, СМЕНА, own_per_hour=40.0),
                _stray_line(710, СМЕНА)):
        assert len(got) <= 60, got


def test_наши_зонды_названы_когда_их_большинство():
    """
    40 зондов в час за 11 часов — примерно 441 из 710, то есть почти две трети.
    Молчать о них здесь значит выдать за посторонних тех, кого создали сами.

    Расчёт сходится с фактом: в журнале nginx за то же время 440 запросов с
    подписью globalping.
    """
    got = _stray_line(710, СМЕНА, own_per_hour=40.0)
    assert "наши зонды ≈441" in got


def test_про_зонды_молчим_когда_их_капля():
    """
    Обратная сторона порога доли. На фоне всплеска те же 441 — это 3%, и
    упоминание лишь удлиняет строку, не добавляя смысла.
    """
    assert "зонды" not in _stray_line(13754, СМЕНА, own_per_hour=40.0)


def test_без_источника_про_зонды_молчим():
    """
    Ноль означает «не знаем». Поправка, взятая из воздуха, хуже отсутствия
    поправки: её потом прочитают как измерение.
    """
    assert "зонды" not in _stray_line(710, СМЕНА, own_per_hour=0.0)


def test_зонды_не_превышают_общего_числа():
    """
    Расчётное число зондов может обогнать измеренный счётчик — например, сразу
    после перезапуска telemt. «Наши зонды ≈440» при сорока соединениях всего
    выглядело бы как ошибка счётчика.
    """
    got = _stray_line(10, СМЕНА, own_per_hour=40.0)
    assert "≈10" in got


def test_без_аптайма_не_падаем_и_не_врём():
    """Аптайм нулевой сразу после старта: скорости нет, делить не на что."""
    got = _stray_line(50, 0)
    assert "/час" not in got
    assert "Не стали клиентами: 50" in got


# --- ЧАСТОТА НАШИХ СОБСТВЕННЫХ ЗОНДОВ --------------------------------

def _settings(tmp_path, text):
    path = tmp_path / "settings.conf"
    path.write_text(text, encoding="utf-8")
    return str(path)


def test_частота_зондов_из_настроек(tmp_path):
    """Настройки стенда: 20 зондов каждые 30 минут — сорок в час."""
    path = _settings(tmp_path, "AVAILABILITY_ENABLED='true'\n"
                               "AVAILABILITY_PROBES='20'\n"
                               "AVAILABILITY_INTERVAL='30'\n")
    assert own_probes_per_hour(path) == 40.0


def test_проверка_выключена_значит_ноль(tmp_path):
    path = _settings(tmp_path, "AVAILABILITY_ENABLED='false'\n"
                               "AVAILABILITY_PROBES='20'\n"
                               "AVAILABILITY_INTERVAL='30'\n")
    assert own_probes_per_hour(path) == 0.0


def test_нет_mtproxyl_значит_ноль(tmp_path):
    assert own_probes_per_hour(str(tmp_path / "нет-такого")) == 0.0


def test_чужой_формат_не_роняет_и_даёт_ноль(tmp_path):
    """
    Мы читаем ЧУЖОЙ файл. Всё, что не разобралось, — «не знаем», а не повод
    падать посреди сводки: правило то же, что и для вердикта доступности.
    """
    for мусор in ("AVAILABILITY_ENABLED='true'\nAVAILABILITY_PROBES='много'\n"
                  "AVAILABILITY_INTERVAL='30'\n",
                  "AVAILABILITY_ENABLED='true'\nAVAILABILITY_INTERVAL='0'\n"
                  "AVAILABILITY_PROBES='20'\n",
                  "{ \"это\": \"вообще json\" }\n",
                  ""):
        assert own_probes_per_hour(_settings(tmp_path, мусор)) == 0.0
