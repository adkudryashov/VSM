"""
Схлопывающаяся цитата в ответах бота.

ЗАЧЕМ ЭТО ПОКРЫВАТЬ. Помощник решает, сворачивать список или оставить как
есть, и ошибиться может в обе стороны, причём молча. Свернёт короткий блок —
человек получит три строки и кнопку вместо четырёх строк содержимого, то есть
чистый убыток. Не свернёт длинный — вернётся стена текста, ради устранения
которой всё и делалось. Ни то, ни другое не роняет бота и в журнале не
появляется: увидеть можно только глазами в чате.

Отдельно проверяется, что заголовок остаётся СНАРУЖИ цитаты. Внутри он
прячется вместе с телом, и в ленте остаётся безымянный серый прямоугольник —
дефект, который замечаешь не сразу, а когда ищешь нужное сообщение среди
десятка одинаковых.
"""

from telemt.utils.helpers import COLLAPSE_MIN_LINES, collapse

ЦИТАТА = "<blockquote expandable>"


def _строки(n: int) -> str:
    return "\n".join(f"строка {i}" for i in range(n))


def test_короткий_блок_не_сворачивается():
    тело = _строки(COLLAPSE_MIN_LINES - 1)
    результат = collapse(тело)
    assert ЦИТАТА not in результат
    assert тело in результат


def test_длинный_блок_сворачивается():
    тело = _строки(COLLAPSE_MIN_LINES)
    результат = collapse(тело)
    assert результат.startswith(ЦИТАТА)
    assert результат.endswith("</blockquote>")
    assert тело in результат


def test_порог_ровно_на_границе():
    """
    Граница проверяется с обеих сторон одним тестом: значение порога не
    «примерно столько», а ровно столько, и сдвиг на строку в любую сторону
    меняет поведение.
    """
    assert ЦИТАТА not in collapse(_строки(COLLAPSE_MIN_LINES - 1))
    assert ЦИТАТА in collapse(_строки(COLLAPSE_MIN_LINES))


def test_заголовок_остаётся_снаружи_цитаты():
    тело = _строки(COLLAPSE_MIN_LINES)
    результат = collapse(тело, "👤 <b>адмін</b> (99)")
    до_цитаты = результат.split(ЦИТАТА)[0]
    assert "👤" in до_цитаты, "заголовок спрятался внутрь — сообщение станет безымянным"


def test_заголовок_сохраняется_и_у_короткого_блока():
    результат = collapse(_строки(2), "👤 заголовок")
    assert "👤 заголовок" in результат
    assert "строка 0" in результат


def test_пустое_тело_отдаёт_только_заголовок():
    assert collapse("", "👤 заголовок") == "👤 заголовок"
    assert collapse("\n\n", "👤 заголовок") == "👤 заголовок"


def test_свой_порог_перекрывает_умолчание():
    """Контрольный случай к порогу: он параметр, а не константа в коде."""
    тело = _строки(3)
    assert ЦИТАТА not in collapse(тело)
    assert ЦИТАТА in collapse(тело, min_lines=3)
