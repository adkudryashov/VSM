"""
Задержка тревоги о падении панели — величина, которую легко испортить молча.

ЗАЧЕМ ЭТО ПОКРЫВАТЬ. Период опроса панелей подняли с минуты до пяти ради
памяти: каждое TLS-соединение оставляет около 100 КБ, которых процесс уже не
отдаёт. Чтобы тревога при этом не стала приходить втрое позже, порог отказов
снизили с десяти до двух — произведение осталось прежним.

Связка держится на двух числах в разных строках конфига. Поднимет кто-нибудь
период ещё раз, не тронув порог, — и о падении панели узнают через час. Ни
тест, ни журнал, ни глаз этого не покажут: всё продолжит работать, просто
медленнее реагировать. Поэтому проверяется само произведение.
"""

from config import settings

# Сколько минут допустимо ждать тревоги о том, что панель упала.
# Десять — то, что было при опросе раз в минуту и десяти отказах.
ПОТОЛОК_МИНУТ = 12


def test_задержка_тревоги_о_падении_панели():
    задержка = (settings.XUI_CHECK_INTERVAL_SECONDS
                * settings.XUI_FAILURES_BEFORE_ALERT) / 60
    assert задержка <= ПОТОЛОК_МИНУТ, (
        "тревога о падении панели придёт через %.0f мин — подняли период "
        "опроса, не снизив порог отказов" % задержка)


def test_порог_отказов_не_единица():
    """
    Обратная сторона: свести порог к единице значило бы кричать на каждую
    сетевую икоту. Два отказа подряд с интервалом в пять минут — уже событие.
    """
    assert settings.XUI_FAILURES_BEFORE_ALERT >= 2


def test_период_опроса_не_вернулся_к_минуте():
    """
    Именно минутный опрос давал 6 МБ утечки в час. Возврат к нему вернёт и
    смерть от нехватки памяти раз в трое суток.
    """
    assert settings.XUI_CHECK_INTERVAL_SECONDS >= 180
