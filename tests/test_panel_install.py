"""
Страж библиотек в panel_install.sh не должен падать на самом себе.

ЗАЧЕМ. panel_install_telemt зовут из двух мест: меню (обычный bash) и
установщик стека (set -euo pipefail). Первым делом функция проверяет, что
подключены нужные ей функции nginx, и накапливает недостающие в переменную.

Переменная объявлялась как `local need` — то есть НЕустановленной. Под set -u
и накопление `need="${need} $fn"`, и сама проверка `[ -n "$need" ]` обращаются
к неустановленной переменной, и оболочка убивает скрипт словами «need: unbound
variable» ещё до того, как страж успеет что-нибудь сказать. Падало это ВСЕГДА,
независимо от того, подключены библиотеки или нет: проверка ломалась о себя.

Из меню всё работало — меню под set -u не ходит. Поэтому установщик стека почти
месяц не мог поставить панель (файл появился 27.08.2026, поймано на установке с
нуля 23.09.2026), и снаружи это выглядело как «панели не установились», без
единого внятного слова о причине.

Отсюда обе стороны проверки: страж обязан СРАБОТАТЬ, когда библиотек нет, и
обязан ПРОПУСТИТЬ, когда они есть. Проверка только первой половины прошла бы и
на сломанной версии — там страж тоже не пропускал никого.
"""
import shutil
import subprocess
import textwrap
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
БИБЛИОТЕКА = КОРЕНЬ / "lib" / "panel_install.sh"

pytestmark = pytest.mark.skipif(
    not БИБЛИОТЕКА.is_file() or shutil.which("bash") is None,
    reason="нужны lib/panel_install.sh и bash",
)

# Ровно тот режим, в котором работает stacks/telemt.sh. Без него проверка
# ничего не значит: под обычным bash сломанная версия вела себя прилично.
СТРОГО = "set -euo pipefail"

# Ровно то, что функция ЗОВЁТ. panel_proxy_localize сюда не входит намеренно:
# панель теперь кладёт установщик своими TP_*, а не мы правим конфиг после него.
НУЖНЫЕ = ("panel_proxy_apply", "panel_proxy_verify", "nginx_mask_panel_vhost")

ЗАГЛУШКИ_NGINX = "".join(f"{имя}() {{ return 0; }}\n" for имя in НУЖНЫЕ)


def bash(скрипт, до_подключения=""):
    """`до_подключения` выполняется ПЕРЕД source — там задают переменные,
    которые библиотека читает при загрузке."""
    полный = (
        f"{СТРОГО}\n{до_подключения}\n"
        f'. "{БИБЛИОТЕКА.as_posix()}"\n{textwrap.dedent(скрипт)}'
    )
    return subprocess.run(
        ["bash", "-c", полный], capture_output=True, text=True, encoding="utf-8"
    )


ВЫЗОВ = (
    "panel_install_telemt admin secret 9444 "
    "panel.example.com rl.example.com abc"
)


def test_без_библиотек_страж_называет_их_а_не_падает():
    ответ = bash(f'{ВЫЗОВ} || echo "КОД=$?"')
    весь = ответ.stdout + ответ.stderr
    assert "unbound variable" not in весь, (
        "страж упал на самом себе вместо того, чтобы назвать причину:\n" + весь
    )
    assert "не подключены библиотеки nginx" in весь, весь


def test_без_библиотек_перечислены_все_недостающие():
    """Назвать одну из трёх мало: остальные пришлось бы искать наугад."""
    ответ = bash(f"{ВЫЗОВ} || true")
    весь = ответ.stdout + ответ.stderr
    for имя in НУЖНЫЕ:
        assert имя in весь, f"{имя} не назван:\n{весь}"


def test_без_библиотек_возвращает_единицу_а_не_убивает_вызывающего():
    """Установщик стека сам решает, что делать с отказом, — он ждёт КОД."""
    ответ = bash(f'{ВЫЗОВ} || echo "КОД=$?"')
    assert "КОД=1" in ответ.stdout + ответ.stderr


def test_с_библиотеками_страж_пропускает():
    """
    Обратная сторона. Без неё проверка прошла бы и на сломанной версии:
    там страж не пропускал никого.

    Следующим шагом функции нужен curl — уводим PATH в пустоту, чтобы она
    остановилась там, а не полезла ставить панель по-настоящему.
    """
    ответ = bash(ЗАГЛУШКИ_NGINX + f'PATH=/несуществующий; {ВЫЗОВ} || echo "КОД=$?"')
    весь = ответ.stdout + ответ.stderr
    assert "unbound variable" not in весь, весь
    assert "не подключены библиотеки" not in весь, (
        "страж не пропустил при всех подключённых функциях:\n" + весь
    )
    assert "нужен curl" in весь, (
        "не дошло до следующей проверки — значит остановилось раньше:\n" + весь
    )


def test_страж_не_требует_того_чего_не_зовёт():
    """
    panel_proxy_localize ушла из списка вместе с вызовом. Страж, требующий
    лишнего, однажды откажет на исправной системе — и верить ему перестанут.
    """
    ответ = bash(ЗАГЛУШКИ_NGINX + f'PATH=/несуществующий; {ВЫЗОВ} || true')
    весь = ответ.stdout + ответ.stderr
    assert "panel_proxy_localize" not in весь, (
        "страж всё ещё требует функцию, которую не зовёт:\n" + весь
    )


def test_отсутствие_одной_функции_тоже_ловится():
    """Две из трёх — это не «подключено»."""
    частично = ЗАГЛУШКИ_NGINX.replace("nginx_mask_panel_vhost() { return 0; }\n", "")
    ответ = bash(частично + f"{ВЫЗОВ} || true")
    весь = ответ.stdout + ответ.stderr
    assert "не подключены библиотеки nginx" in весь, весь
    assert "nginx_mask_panel_vhost" in весь
    assert "panel_proxy_apply" not in весь, (
        "названа подключённая функция — список собран неверно:\n" + весь
    )


def test_версия_панели_задана_явно():
    """
    Умолчание установщика — «последняя стабильная», то есть 0.6.2, а её он
    поставить не может: контрольные суммы там названы иначе, чем он ищет.
    Пустая переменная вернула бы установку в это состояние молча.
    """
    ответ = bash('echo "[${TELEMT_PANEL_VERSION}]"')
    assert ответ.stdout.strip() not in ("[]", ""), (
        "версия панели не задана — установщик уйдёт за 0.6.2 и остановится"
    )
    assert ответ.stdout.strip().startswith("[v"), ответ.stdout


def test_версию_можно_переопределить_снаружи():
    """
    Откат на другую версию должен быть возможен без правки файла: ровно так
    XUI_VERSION однажды спас установку 3x-ui. Задаём ДО подключения —
    библиотека читает переменную при загрузке.
    """
    ответ = bash(
        'echo "[${TELEMT_PANEL_VERSION}]"',
        до_подключения="TELEMT_PANEL_VERSION=v9.9.9",
    )
    assert "[v9.9.9]" in ответ.stdout, (
        "версия прибита жёстко — отката на другую не будет:\n" + ответ.stdout
    )
