"""
Перевод панели на петлю разбирает конфиг по секциям, а не правит вслепую.

ЗАЧЕМ. panel_proxy_localize снимает с telemt_panel собственный TLS: снаружи
админ-форма с валидным сертификатом на нестандартном порту — самый громкий
объект на сервере, и вся работа по маскировке порта telemt после неё теряет
смысл. TLS терминирует nginx на 443 домена панели.

Формат секции [tls] у панели сменился:

    0.x   [tls] cert_file = ... / key_file = ...
    1.x   [tls] mode = "http" | "acme" | "certificate" | "proxy"

Прежняя правка удаляла строку [tls] вместе с ключами. На 1.x это оставило бы
mode висеть в КОРНЕ файла: панель теряет режим транспорта и получает лишний
ключ верхнего уровня.

Соблазн починить это одним `sed s/mode = .*/mode = "http"/` по всему файлу —
ловушка, ради которой и написан этот файл проверок: в 1.x есть ВТОРАЯ секция с
тем же ключом, [privileges] mode = "sudo". Такая правка заменила бы «узкая
политика sudo» на «http», а панель при непонятном значении легко могла бы
откатиться к работе от root. То есть косметическая правка конфига раздавала бы
права. Поэтому здесь у каждой проверки есть сосед: что тронули — и что НЕ
тронули.
"""
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parent.parent
БИБЛИОТЕКА = КОРЕНЬ / "lib" / "nginx_panel_proxy.sh"

pytestmark = pytest.mark.skipif(
    not БИБЛИОТЕКА.is_file() or shutil.which("bash") is None,
    reason="нужны lib/nginx_panel_proxy.sh и bash",
)

КОНФИГ_1X = """\
listen = "0.0.0.0:9444"
base_path = ""
data_dir = "/var/lib/telemt-panel"

[tls]
mode = "acme"

[telemt]
url = "http://127.0.0.1:9091"

[auth]
username = "admin"

[privileges]
mode = "sudo"
"""

КОНФИГ_0X = """\
listen = "0.0.0.0:9444"

[tls]
cert_file = "/etc/letsencrypt/live/r.example.com/fullchain.pem"
key_file = "/etc/letsencrypt/live/r.example.com/privkey.pem"

[auth]
username = "admin"
"""


# Аргументы передаются ПОЗИЦИОННО, а не подстановкой в командную строку.
#
# Первая редакция собирала строку через f-string, и значение порта попадало в
# bash -c как код. Проверка «нечисловой порт отвергается» брала образцом
# `9444; rm -rf /` — и эта команда выполнилась В САМОМ ТЕСТЕ на стенде, а не
# внутри проверяемой функции; остановил её только предохранитель coreutils.
# Проверка при этом «работала»: она видела ненулевой код возврата и считала,
# что сработала защита функции. Замерено 23.09.2026.
#
# Отсюда два правила этого файла: аргументы уходят через argv, а образцом
# плохого значения служит безобидная строка — разрушительная в фикстуре не
# нужна никогда.
ВЫЗОВ = f'. "{БИБЛИОТЕКА.as_posix()}"\npanel_proxy_localize "$1" "$2" "$3"'

# СИСТЕМНЫЕ КОМАНДЫ — ТОЛЬКО ПОДДЕЛЬНЫЕ.
#
# panel_proxy_localize после правки конфига перезапускает службу панели, снимает
# ACL с /etc/letsencrypt и закрывает порт в ufw. Первая редакция этого файла
# звала её с настоящим PATH — и каждый прогон тестов на стенде перезапускал
# НАСТОЯЩУЮ telemt-panel, около дюжины раз за секунду. Пока панели на стенде не
# было, systemctl молча отказывал, и никто ничего не замечал. 23.09.2026 стенд
# перевели на telemt_panel, и два прогона подряд довели её до start-limit-hit:
# панель лежала, по секретному пути шёл 404, и первым подозреваемым был nginx.
#
# Поэтому здесь PATH начинается с каталога заглушек, а заглушка systemctl
# записывает, о чём её просили: так видно, что функция действительно пыталась
# перезапустить службу, — и что до настоящей systemd это не дошло.
ЗАГЛУШКИ = ("systemctl", "setfacl", "ufw", "id")
_КАТАЛОГ_ЗАГЛУШЕК = Path(tempfile.mkdtemp(prefix="vsm-stubs-"))
ЖУРНАЛ = _КАТАЛОГ_ЗАГЛУШЕК / "вызовы.log"
for _имя in ЗАГЛУШКИ:
    _f = _КАТАЛОГ_ЗАГЛУШЕК / _имя
    _f.write_text(f'#!/bin/sh\necho "{_имя} $*" >> "{ЖУРНАЛ.as_posix()}"\nexit 0\n')
    _f.chmod(0o755)


def окружение():
    """Единственный способ запустить функцию в этом файле — с заглушками."""
    env = dict(os.environ)
    env["PATH"] = f"{_КАТАЛОГ_ЗАГЛУШЕК.as_posix()}:{env.get('PATH', '')}"
    return env


def перевести(текст, tmp_path, порт="9444"):
    файл = tmp_path / "config.toml"
    файл.write_text(текст, encoding="utf-8")
    ответ = subprocess.run(
        ["bash", "-c", ВЫЗОВ, "vsm-test",
         файл.as_posix(), str(порт), "r.example.com"],
        capture_output=True, text=True, encoding="utf-8", env=окружение(),
    )
    return файл.read_text(encoding="utf-8"), ответ


# --- 1.x -------------------------------------------------------------------

def test_1x_режим_tls_становится_http(tmp_path):
    текст, ответ = перевести(КОНФИГ_1X, tmp_path)
    assert ответ.returncode == 0, ответ.stderr
    assert '[tls]' in текст, "заголовок [tls] удалён — mode повис бы в корне"
    assert 'mode = "http"' in текст, текст
    assert 'mode = "acme"' not in текст, текст


def test_1x_права_панели_не_тронуты(tmp_path):
    """Сосед предыдущей проверки. Слепой sed выдал бы панели root."""
    текст, _ = перевести(КОНФИГ_1X, tmp_path)
    assert 'mode = "sudo"' in текст, (
        "затёрт [privileges] mode — панель получила бы не те права:\n" + текст
    )
    assert текст.count('mode = "http"') == 1, (
        "«http» появился больше одного раза — правка ушла не в ту секцию:\n" + текст
    )


def test_1x_секция_privileges_цела(tmp_path):
    текст, _ = перевести(КОНФИГ_1X, tmp_path)
    строки = текст.splitlines()
    начало = строки.index("[privileges]")
    assert 'mode = "sudo"' in строки[начало:], текст


def test_1x_остальной_конфиг_на_месте(tmp_path):
    текст, _ = перевести(КОНФИГ_1X, tmp_path)
    for кусок in ('base_path = ""', 'data_dir = "/var/lib/telemt-panel"',
                  '[telemt]', 'url = "http://127.0.0.1:9091"',
                  '[auth]', 'username = "admin"'):
        assert кусок in текст, f"{кусок} потерян:\n{текст}"


# --- 0.x -------------------------------------------------------------------

def test_0x_свой_сертификат_убран(tmp_path):
    текст, ответ = перевести(КОНФИГ_0X, tmp_path)
    assert ответ.returncode == 0, ответ.stderr
    assert "cert_file" not in текст, текст
    assert "key_file" not in текст, текст
    assert "[tls]" not in текст, текст


def test_0x_остальной_конфиг_на_месте(tmp_path):
    текст, _ = перевести(КОНФИГ_0X, tmp_path)
    assert "[auth]" in текст and 'username = "admin"' in текст, текст


# --- общее -----------------------------------------------------------------

@pytest.mark.parametrize("конфиг", [КОНФИГ_1X, КОНФИГ_0X])
def test_панель_переезжает_на_петлю(tmp_path, конфиг):
    """Ради этого функция и существует."""
    текст, ответ = перевести(конфиг, tmp_path)
    assert ответ.returncode == 0, ответ.stderr
    assert 'listen = "127.0.0.1:9444"' in текст, текст
    assert '0.0.0.0' not in текст, текст


@pytest.mark.parametrize("плохой", ["", "девять", "9444abc", "94 44", "-1"])
def test_нечисловой_порт_отвергается(tmp_path, плохой):
    """
    Обратная сторона: что угодно кроме числа не должно уехать в конфиг.
    Функция подставляет порт в listen через sed, поэтому мусор здесь —
    это мусор в чужом конфиге.
    """
    текст, ответ = перевести(КОНФИГ_1X, tmp_path, порт=плохой)
    assert ответ.returncode != 0, f"порт '{плохой}' принят"
    assert "числовой порт" in ответ.stderr, ответ.stderr
    assert текст == КОНФИГ_1X, "конфиг тронут при отказе:\n" + текст


def test_отсутствующий_файл_называется(tmp_path):
    ответ = subprocess.run(
        ["bash", "-c", ВЫЗОВ, "vsm-test",
         (tmp_path / "нет.toml").as_posix(), "9444", "r.example.com"],
        capture_output=True, text=True, encoding="utf-8", env=окружение(),
    )
    assert ответ.returncode != 0
    assert "не найден конфиг панели" in ответ.stderr, ответ.stderr


def test_перезапуск_ушёл_в_заглушку_а_не_в_систему(tmp_path):
    """
    Функция ДЕЙСТВИТЕЛЬНО просит перезапустить службу — и просьба приходит к
    заглушке. Без этой проверки заглушки могли бы тихо перестать
    перехватывать вызов, и тесты снова начали бы трогать настоящую систему.
    """
    ЖУРНАЛ.write_text("", encoding="utf-8")
    перевести(КОНФИГ_1X, tmp_path)
    журнал = ЖУРНАЛ.read_text(encoding="utf-8")
    assert "systemctl restart telemt-panel" in журнал, (
        "заглушка systemctl не получила вызова — значит он ушёл мимо неё:\n" + журнал
    )


def test_ни_один_вызов_функции_не_идёт_без_заглушек():
    """Сторож файла: subprocess.run здесь обязан получать env=окружение()."""
    текст = Path(__file__).read_text(encoding="utf-8")
    вызовов = текст.count("subprocess.run(")
    с_заглушками = текст.count("env=окружение()")
    assert вызовов == с_заглушками, (
        f"subprocess.run {вызовов}, а с заглушками {с_заглушками} — "
        "какой-то вызов пойдёт в настоящую систему"
    )


def test_временный_файл_не_остаётся(tmp_path):
    """Забытый config.toml.vsm.XXXX в /etc/telemt-panel — чужой каталог."""
    перевести(КОНФИГ_1X, tmp_path)
    остатки = [p.name for p in tmp_path.iterdir() if p.name != "config.toml"]
    assert остатки == [], f"осталось лишнее: {остатки}"
