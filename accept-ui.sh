#!/bin/bash
#
# Приёмка меню. Запускается НА СЕРВЕРЕ, где VSM установлен.
#
# Зачем отдельно от check-ui.sh: та читает исходники, эта запускает. За сессию
# переделки оформления одиннадцать дефектов нашлись так — пять в живом
# терминале, ноль статикой. Читать код оказалось недостаточно.
#
# ЧЕГО ЭТА ПРИЁМКА НЕ ДЕЛАЕТ: она не жмёт разрушающие пункты. Слепо прогнать
# все клавиши подряд на живом сервере значит снести стек — установка, удаление
# и правка фаервола исключены поимённо, а не по догадке.
#
# Запуск: bash accept-ui.sh
# Возврат: 0 — чисто, 1 — есть находки.

cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" || exit 1

BIN=/usr/local/bin
FAIL=0
say()  { echo -e "\033[0;36m$*\033[0m"; }
bad()  { echo -e "\033[0;31m  ✗ $*\033[0m"; FAIL=1; }
ok()   { echo -e "\033[0;32m  ✓ $*\033[0m"; }
note() { echo -e "\033[0;90m    $*\033[0m"; }

MENUS=(vsm menu_xui.sh menu_telemt.sh menu_awg.sh menu_bots.sh
       menu_setup.sh menu_tests.sh menu_utils.sh menu_warp.sh)

# Признаки того, что скрипт сломался, а не отработал. Ищем в выводе, потому что
# код возврата у меню ничего не значит: цикл завершается по X и возвращает 0
# даже если внутри сыпались ошибки.
ERRPAT='command not found|unbound variable|syntax error|No such file or directory|integer expression expected|too many arguments|bad substitution'

# ---------------------------------------------------------------------------
# 1. Каждый экран открывается и не сыплет ошибками
#
# Без TTY и с ограничением по времени: при закрытом stdin цикл меню крутится
# вечно — это уже ловили. Цвет снимается сам, потому что вывод не в терминал.
# ---------------------------------------------------------------------------
say "1. Экраны открываются без ошибок оболочки"
for m in "${MENUS[@]}"; do
    out=$(printf 'X\nX\nX\n' | timeout 40 bash "${BIN}/${m}" 2>&1)
    hits=$(grep -inE "$ERRPAT" <<< "$out" | head -3)
    if [ -n "$hits" ]; then
        bad "$m"
        sed 's/^/      /' <<< "$hits"
    elif [ "$(wc -c <<< "$out")" -lt 200 ]; then
        bad "$m: экран почти пуст ($(wc -c <<< "$out") байт) — вероятно, упал молча"
    else
        ok "$m"
    fi
done

# ---------------------------------------------------------------------------
# 2. У каждой показанной клавиши есть ветка обработки
#
# Ровно тот дефект, который владелец нашёл глазами: пункты перегруппировали, а
# клавиши остались прежние. Обратная сторона той же ошибки страшнее — клавиша
# показана, а ветки под неё нет, и нажатие молча ничего не делает.
#
# Проверяем только это направление. «Ветка есть, а пункт не показан» — не
# дефект: во вложенных меню свои case с теми же цифрами.
# ---------------------------------------------------------------------------
say "2. Показанная клавиша имеет ветку обработки"
found=0
for m in "${MENUS[@]}"; do
    keys=$(grep -oE 'ui_(danger_)?item +"[0-9]+"' "$m" 2>/dev/null \
           | grep -oE '[0-9]+' | sort -un)
    for k in $keys; do
        if ! grep -qE "^[[:space:]]*(${k}\)|[0-9|]*\|${k}\)|${k}\|)" "$m"; then
            bad "$m: клавиша ${k} показана, но ветки под неё нет"
            found=1
        fi
    done
done
[ "$found" -eq 0 ] && ok "все показанные клавиши обрабатываются"

# ---------------------------------------------------------------------------
# 3. Безопасные пункты действительно работают
#
# Поимённо и только те, что ничего не меняют. Каждый проверяется по признаку в
# выводе, а не по коду возврата: меню возвращает 0 почти всегда.
# ---------------------------------------------------------------------------
say "3. Безопасные пункты открываются и делают своё"
drive() { # файл ввод признак описание
    local f="$1" keys="$2" want="$3" desc="$4" out
    out=$(printf '%b' "$keys" | timeout 40 bash "${BIN}/${f}" 2>&1)
    if grep -qiE "$ERRPAT" <<< "$out"; then
        bad "$desc: ошибка оболочки"
        grep -inE "$ERRPAT" <<< "$out" | head -2 | sed 's/^/      /'
    elif grep -qiE "$want" <<< "$out"; then
        ok "$desc"
    else
        bad "$desc: в выводе нет признака «${want}»"
    fi
}
#
# Признак берётся из вывода ДЕЙСТВИЯ, а не из названия пункта.
#
# Первая редакция искала «Активные порты» — и проходила, потому что эта строка
# есть в самом списке меню. Проверка «работает ли пункт» отвечала «да», ни разу
# его не открыв. Плюс ввод начинался с X, который выходит из меню сразу же: до
# нужной клавиши дело не доходило вовсе.
#
# Отсюда правило для этого файла: признак обязан быть строкой, которой в
# списке пунктов НЕТ.
drive menu_utils.sh  '4\n3\n\nX\n'  'Netid|LISTEN|UNCONN'    'утилиты: порты (клавиша 4)'
drive menu_utils.sh  '5\n\nX\n'     'Проверка IP'            'утилиты: внешний адрес (клавиша 5)'
drive menu_xui.sh    '3\nX\nX\n'    'УЧЁТНЫЕ ДАННЫЕ ПАНЕЛИ'  'X-UI: учётные данные (клавиша 3)'
drive menu_awg.sh    '2\nX\nX\n'    'LABEL.*PUBLIC_KEY'      'AWG: клиенты (клавиша 2)'
drive menu_awg.sh    '4\n\nX\n'     'iface=awg0'             'AWG: журнал (клавиша 4)'
drive menu_telemt.sh '6\n\nX\n'     'УЧЁТНЫЕ ДАННЫЕ СТЕКА'   'telemt: учётные данные (клавиша 6)'

# ---------------------------------------------------------------------------
# 3б. Обработчики действий внутри подменю
#
# Переделка оформления шла по ГЛАВНЫМ экранам, а `clear 2>/dev/null` был
# прогнан слепым sed по девяти файлам. Значит обработчики трогали, но не
# открывали ни разу.
#
# Здесь открывается каждый экран второго уровня и проверяется, что оболочка не
# сыплет ошибками. Ничего не подтверждается: там, где обработчик спрашивает
# подтверждение, ввод обрывается пустой строкой и выходом.
#
# Признака в выводе не требуем — экраны разные, и половина зависит от того,
# что установлено. Ищем ровно поломку.
# ---------------------------------------------------------------------------
say "3б. Обработчики действий второго уровня"
screen() { # файл ввод описание
    local out; out=$(printf '%b' "$2" | timeout 60 bash "${BIN}/$1" 2>&1)
    local hits; hits=$(grep -inE "$ERRPAT" <<< "$out" | head -2)
    if [ -n "$hits" ]; then
        bad "$3"
        sed 's/^/      /' <<< "$hits"
    else
        ok "$3"
    fi
}
screen menu_xui.sh    '4\nX\nX\nX\n'      'X-UI: бэкапы (4)'
screen menu_xui.sh    '5\n1\n\nX\nX\n'    'X-UI: служба, статус (5→1)'
screen menu_xui.sh    '7\nX\nX\nX\n'      'X-UI: AdGuard (7)'
screen menu_telemt.sh '3\n\nX\n'          'telemt: диагностика (3)'
screen menu_telemt.sh '7\n1\n1\n\nX\nX\n' 'telemt: служба telemt, статус (7→1→1)'
screen menu_telemt.sh '8\nX\nX\n'         'telemt: MTProxyL (8)'
screen menu_telemt.sh '9\n\n\nX\n'        'telemt: экран пересборки nginx (9, без подтверждения)'
screen menu_awg.sh    '3\n\nX\n'          'AWG: проверка обновлений (3)'
screen menu_bots.sh   '6\n\nX\n'          'боты: настройки (6)'
screen menu_bots.sh   '7\nX\nX\n'         'боты: управление службами (7)'
screen menu_setup.sh  '1\nX\nX\n'         'настройка: BBR (1)'
screen menu_setup.sh  '2\nX\nX\n'         'настройка: ICMP (2)'
screen menu_setup.sh  '3\nX\nX\n'         'настройка: UFW (3, без включения)'
screen menu_setup.sh  '5\nX\nX\n'         'настройка: SSL (5)'
screen menu_setup.sh  '6\nX\nX\n'         'настройка: часовой пояс (6)'
screen menu_warp.sh   '2\n\nX\n'          'WARP: порт (2)'
screen menu_warp.sh   '4\nX\nX\n'         'WARP: служба (4)'
screen menu_utils.sh  '2\n4\n\nX\n'       'утилиты: ncdu, свой путь (2→4)'
screen menu_utils.sh  '7\n\n\nX\n'        'утилиты: привязка домена (7)'
screen menu_utils.sh  '8\nX\nX\n'         'утилиты: очистка (8, без подтверждения)'

# ---------------------------------------------------------------------------
# 4. Конвертер в mihomo — с контрольными случаями
#
# У каждой отрицательной проверки есть положительная пара. Без неё проверка
# может «проходить», ничего не проверяя: за эту сессию так вышло трижды —
# узкий терминал, конфиг с примешанным stderr и netns без своего resolv.conf.
# Все три давали ложный результат, потому что я не показывал, что тест вообще
# способен сработать в плюс.
# ---------------------------------------------------------------------------
say "4. Конвертер awg2mihomo"
CONV=./awg2mihomo.sh
GOOD=$(printf '[Interface]\nPrivateKey = kkk\nAddress = 10.99.0.5/32\nDNS = 1.1.1.1, 8.8.8.8\nMTU = 1280\nJc = 4\nS1 = 7\nH1 = 1-2\nI1 = <b 0xaa><t>\n[Peer]\nPublicKey = ppp\nPresharedKey = sss\nAllowedIPs = 0.0.0.0/0, ::/0\nEndpoint = example.com:51820\nPersistentKeepalive = 25\n')

t_ok() { # описание ввод ожидаемая-подстрока
    local out; out=$(printf '%s' "$2" | bash "$CONV" - 2>/dev/null)
    if grep -qF -- "$3" <<< "$out"; then ok "$1"; else bad "$1: нет «$3»"; note "$(head -3 <<< "$out")"; fi
}
t_fail() { # описание ввод
    local out rc
    out=$(printf '%s' "$2" | bash "$CONV" - 2>/dev/null); rc=$?
    if [ "$rc" -ne 0 ] && [ -z "$out" ]; then ok "$1"; else bad "$1: ожидался отказ, получен код ${rc} и $(wc -c <<< "$out") байт"; fi
}

t_ok   "домен в Endpoint переносится как есть" "$GOOD" "server: example.com"
t_ok   "маска у адреса клиента снимается"      "$GOOD" "ip: 10.99.0.5"
t_ok   "имя ключа pre-shared-key"              "$GOOD" "pre-shared-key:"
t_ok   "keepalive не теряется"                 "$GOOD" "persistent-keepalive: 25"
t_ok   "два резолвера списком"                 "$GOOD" "dns: [1.1.1.1, 8.8.8.8]"
t_ok   "обфускация во вложенном блоке"         "$GOOD" "    amnezia-wg-option:"
t_ok   "::/0 отброшен"                         "$GOOD" "allowed-ips: ['0.0.0.0/0']"
t_fail "отказ на 3.0"            "$(printf '%s\nHeaderProtectionKey = z\n' "$GOOD")"
t_fail "отказ без Endpoint"      "$(grep -v '^Endpoint' <<< "$GOOD")"
t_fail "отказ без PrivateKey"    "$(grep -v '^PrivateKey' <<< "$GOOD")"
t_fail "отказ на пустом вводе"   ""

# Контрольный случай к отказам: тот же проверяющий обязан пропускать годное.
# Без него «отказ сработал» ничего не значит — он мог отказывать всему подряд.
out=$(printf '%s' "$GOOD" | bash "$CONV" - 2>/dev/null)
if [ -n "$out" ]; then ok "контроль: годный конфиг НЕ отвергается"; else bad "контроль: отвергается даже годный конфиг"; fi

# Разбор YAML, если есть чем. Значения i1-i5 содержат угловые скобки, и то, что
# YAML их принимает, стоит проверять, а не предполагать.
if command -v python3 >/dev/null 2>&1 && python3 -c 'import yaml' 2>/dev/null; then
    if printf '%s' "$GOOD" | bash "$CONV" - 2>/dev/null | python3 -c '
import sys, yaml
p = yaml.safe_load(sys.stdin)["proxies"][0]
assert p["type"] == "wireguard"
assert "amnezia-wg-option" in p
assert isinstance(p["dns"], list) and len(p["dns"]) == 2
' 2>/dev/null; then
        ok "вывод разбирается yaml.safe_load"
    else
        bad "вывод НЕ разбирается yaml.safe_load"
    fi
else
    note "python3 с yaml нет — разбор YAML пропущен"
fi

echo
if [ "$FAIL" -eq 0 ]; then
    echo -e "\033[0;32mПриёмка меню: находок нет.\033[0m"
else
    echo -e "\033[0;31mПриёмка меню: есть находки, см. выше.\033[0m"
fi
exit "$FAIL"
